"""Generates src/zeta_data.cyr: Euler's γ and ζ(k), k = 2 … 64, as double-doubles (M2 part b4; port plan §5 step
9d-2, §3.4; ADR 009).

The T1 incomplete gamma (src/gammainc.cyr, probe P9's prototype) takes lnΓ(a) below a = 10 from the series
lnΓ(1 + f) = −γf + Σ (−1)^k ζ(k)/k·f^k and lnΓ(2 + y) = (1 − γ)y + Σ (−1)^k (ζ(k) − 1)/k·y^k (k ≥ 2), so it needs
these constants to double-double precision. MPFR computes each at 320 bits; hi = RN(v) and lo = RN(v − hi), and the
pair must be within 2^-104 of v or the script fails. ζ(k) − 1 is taken in MPFR before the split. This is probe P9's
scripts/probes/p9_zeta_table.c through ctypes; it writes the same bits. Constants are generated, never typed by hand
(CLAUDE.md).

    python3 -I -B scripts/gen_zeta.py .            # write src/zeta_data.cyr
    python3 -I -B scripts/gen_zeta.py . --check    # exit 1 when it differs from what MPFR gives, or an inline word
                                                   # in src/dd.cyr or src/gammainc.cyr isn't proven

`--check` also proves the inline hex words of src/dd.cyr and src/gammainc.cyr: each 16-digit word in code is the power
of two its comment cites (`0x3C10000000000000  # 0x1p-62`). Without MPFR it checks those alone and reports the table
"unverified". MPFR (libmpfr.so.6) is called through ctypes; stdlib only.
"""

import ctypes
import ctypes.util
import os
import re
import struct
import sys

ROOT = os.path.abspath(sys.argv[1] if len(sys.argv) > 1 and not sys.argv[1].startswith("-") else ".")
CHECK = "--check" in sys.argv
OUT = os.path.join(ROOT, "src", "zeta_data.cyr")
INLINE = ("src/dd.cyr", "src/gammainc.cyr")


def bits(d: float) -> int:
    return struct.unpack("<Q", struct.pack("<d", d))[0]


def mpfr():
    lib = ctypes.util.find_library("mpfr") or "libmpfr.so.6"
    try:
        return ctypes.CDLL(lib)
    except OSError:
        return None


def table_values(m):
    """(γ, [ζ(k)], [ζ(k) − 1]) as (hi, lo) pairs, k = 0 … 64 (0 and 1 are (0, 0))."""
    t = ctypes.c_byte * 32
    P = ctypes.c_void_p
    m.mpfr_init2.argtypes = [P, ctypes.c_long]
    m.mpfr_const_euler.argtypes = [P, ctypes.c_int]
    m.mpfr_zeta_ui.argtypes = [P, ctypes.c_ulong, ctypes.c_int]
    m.mpfr_sub_ui.argtypes = [P, P, ctypes.c_ulong, ctypes.c_int]
    m.mpfr_sub_d.argtypes = [P, P, ctypes.c_double, ctypes.c_int]
    m.mpfr_div.argtypes = [P, P, P, ctypes.c_int]
    m.mpfr_abs.argtypes = [P, P, ctypes.c_int]
    m.mpfr_cmp_d.argtypes = [P, ctypes.c_double]
    m.mpfr_get_d.argtypes = [P, ctypes.c_int]
    m.mpfr_get_d.restype = ctypes.c_double
    v, r, e = t(), t(), t()
    for x in (v, r, e):
        m.mpfr_init2(ctypes.byref(x), 320)
    rn = 0

    def split(name):
        hi = m.mpfr_get_d(ctypes.byref(v), rn)
        m.mpfr_sub_d(ctypes.byref(r), ctypes.byref(v), hi, rn)
        lo = m.mpfr_get_d(ctypes.byref(r), rn)
        m.mpfr_sub_d(ctypes.byref(e), ctypes.byref(r), lo, rn)
        m.mpfr_div(ctypes.byref(e), ctypes.byref(e), ctypes.byref(v), rn)
        m.mpfr_abs(ctypes.byref(e), ctypes.byref(e), rn)
        if m.mpfr_cmp_d(ctypes.byref(e), 2.0 ** -104) > 0:
            sys.exit(f"{name}: hi + lo misses by more than 2^-104")
        return hi, lo

    m.mpfr_const_euler(ctypes.byref(v), rn)
    euler = split("γ")
    zeta, zm1 = [(0.0, 0.0)] * 2, [(0.0, 0.0)] * 2
    for k in range(2, 65):
        m.mpfr_zeta_ui(ctypes.byref(v), k, rn)
        zeta.append(split(f"ζ({k})"))
        m.mpfr_sub_ui(ctypes.byref(v), ctypes.byref(v), 1, rn)
        zm1.append(split(f"ζ({k}) − 1"))
    return euler, zeta, zm1


def render(m) -> str:
    m.mpfr_get_version.restype = ctypes.c_char_p
    version = m.mpfr_get_version().decode()
    euler, zeta, zm1 = table_values(m)
    out = [
        "# zeta_data.cyr — Euler's γ and ζ(k), k = 2 … 64, as double-doubles, for the T1 incomplete gamma's lnΓ below",
        "# a = 10 (M2 part b4; port plan §5 step 9d-2, ADR 009).",
        "#",
        f"# GENERATED by scripts/gen_zeta.py from MPFR {version.split('.')[0]}.x at 320 bits. Do not edit. Each constant is a",
        "# double-double, hi = RN(v) and lo = RN(v − hi), checked to 2^-104, held as bit patterns: γ as two typed",
        "# globals, and ζ(k) (ZH, ZL) and ζ(k) − 1 (MH, ML, taken in MPFR before the split) as tables indexed by k, with",
        "# k = 0 and 1 unused.",
        "",
        f"var _PMN_ZT_EULER_H: f64 = 0x{bits(euler[0]):016X};   # {euler[0]!r}",
        f"var _PMN_ZT_EULER_L: f64 = 0x{bits(euler[1]):016X};",
    ]
    for name, col in (("ZH", [p[0] for p in zeta]), ("ZL", [p[1] for p in zeta]),
                      ("MH", [p[0] for p in zm1]), ("ML", [p[1] for p in zm1])):
        words = [f"0x{bits(w):016X}" for w in col]
        rows = [", ".join(words[i:i + 4]) for i in range(0, 65, 4)]
        out.append(f"var _PMN_ZT_{name}: i64[65] = {{")
        out += [f"    {row}{',' if i < len(rows) - 1 else ''}" for i, row in enumerate(rows)]
        out.append("};")
    return "\n".join(out) + "\n"


def inline_failures() -> list:
    fails = []
    for rel in INLINE:
        path = os.path.join(ROOT, rel)
        if not os.path.exists(path):
            continue
        for n, line in enumerate(open(path, encoding="utf-8").read().splitlines(), 1):
            code, _, comment = line.partition("#")
            for w in re.findall(r"0x[0-9A-Fa-f]{16}\b", code):
                cited = re.findall(r"0x1p(-?\d+)", comment)
                if not cited or int(w, 16) != bits(2.0 ** int(cited[0])):
                    fails.append(f"{rel}:{n}: {w} is not the power of two its comment cites")
            for w in re.findall(r"0x[0-9A-Fa-f]+\b", code):
                if len(w) != 18:
                    fails.append(f"{rel}:{n}: {w} is not a 16-digit word this check can prove")
    return fails


def main() -> int:
    m = mpfr()
    fails = inline_failures()
    if m is None:
        if CHECK:
            for f in fails:
                print("FAILED:", f)
            print("gen_zeta: " + (f"{len(fails)} failures" if fails else
                                  "table unverified (no MPFR); every inline word proven"))
            return 1 if fails else 0
        sys.exit("cannot load libmpfr")
    text = render(m)
    if CHECK:
        if not (os.path.exists(OUT) and open(OUT, encoding="utf-8").read() == text):
            fails.insert(0, "src/zeta_data.cyr differs from what MPFR gives")
        for f in fails:
            print("FAILED:", f)
        print("gen_zeta: " + (f"{len(fails)} failures" if fails else
                              "ok (γ and ζ(2 … 64) from MPFR; every inline word proven)"))
        return 1 if fails else 0
    open(OUT, "w", encoding="utf-8").write(text)
    print(f"wrote src/zeta_data.cyr ({text.count(chr(10))} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())

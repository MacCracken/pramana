"""Vendors fdlibm's lgamma coefficients into src/lgamma_data.cyr (M2 part b3; port plan D3 = C, §3.4; ADR 009).

pramana's T1 lnΓ (src/lgamma.cyr, probe P9's prototype, §5 step 9d-1) is fdlibm's e_lgamma_r layout with
double-double logarithms and products. Its coefficients are FreeBSD's, as the libm crate 0.2.16 carries them in
`src/math/lgamma_r.rs` (a transcription of e_lgamma_r.c), read from the cargo registry and pinned by sha256. Each
`const NAME: f64 = <decimal>; /* 0xHI, 0xLO */` line is proven twice: the decimal literal must parse to the bits in
its hex comment, or the script fails. Constants are generated, never typed by hand (CLAUDE.md).

    python3 -I -B scripts/vendor_lgamma.py .            # write src/lgamma_data.cyr
    python3 -I -B scripts/vendor_lgamma.py . --check    # exit 1 when it differs from what the source gives, or
                                                        # an inline word in src/lgamma.cyr isn't proven

`--check` also proves src/lgamma.cyr's inline hex words: each 16-digit word is a power of two whose comment cites it
(`0x7DD0000000000000   # 0x1p990`), and each 8-digit high-word threshold occurs in lgamma_r.rs, verbatim or as
its `(0x3ff - 70) << 20` form.

Without the registry copy (CI checks out pramana alone), `--check` reports "unverified" and exits 0. Adapted from
probe P9's scripts/probes/p9_fdlibm_consts.py. Stdlib only.
"""

import glob
import hashlib
import os
import re
import struct
import sys

ROOT = os.path.abspath(sys.argv[1] if len(sys.argv) > 1 and not sys.argv[1].startswith("-") else ".")
CHECK = "--check" in sys.argv
SOURCE = "libm-0.2.16/src/math/lgamma_r.rs"
SHA256 = "5d56169c077b5b9f88902e2d243a7a4b4d06b89295aa84283d6fa15d9c244032"
OUT = os.path.join(ROOT, "src", "lgamma_data.cyr")
LINE = re.compile(r"^const (\w+): f64 = ([-+0-9.eE]+); /\* (0x[0-9A-Fa-f]{8}), (0x[0-9A-Fa-f]{8}) \*/$")


def render(text: str) -> str:
    notice = text[: text.index("*/", text.index("Copyright")) + 2]
    consts = []
    for line in text.splitlines():
        m = LINE.match(line.strip())
        if not m:
            continue
        name, dec, hi, lo = m.groups()
        bits = (int(hi, 16) << 32) | int(lo, 16)
        parsed = struct.unpack("<Q", struct.pack("<d", float(dec)))[0]
        if parsed != bits:
            sys.exit(f"{name}: {dec} parses to {parsed:016x}, the comment says {bits:016x}")
        consts.append((name, bits, dec))
    if len(consts) < 60:
        sys.exit(f"only {len(consts)} constants found; the source changed")
    out = [
        "# lgamma_data.cyr — fdlibm's lgamma coefficients, for the T1 lnΓ (M2 part b3; port plan §3.4, ADR 009).",
        "#",
        "# GENERATED by scripts/vendor_lgamma.py from the libm crate 0.2.16's src/math/lgamma_r.rs (sha256",
        f"# {SHA256[:16]}…), a transcription of FreeBSD's e_lgamma_r.c. Do not edit. Each value is a typed",
        "# global holding its bit pattern, which the generator checked against the decimal literal. The source's",
        "# notice, which its licence asks to keep:",
        "#",
    ]
    out += [("# " + row).rstrip() for row in notice.splitlines()]
    out.append("")
    out += [f"var _PMN_LG_{name}: f64 = 0x{bits:016X};   # {dec}" for name, bits, dec in consts]
    return "\n".join(out) + "\n"


def inline_failures(port: str, source: str) -> list:
    fails = []
    words_src = {w.lower() for w in re.findall(r"0x[0-9a-fA-F]{8}\b", source)}
    # libm writes one threshold as an expression, `(0x3ff - 70) << 20` (|x| < 2^-70): evaluate that form too.
    for base, sub, sh in re.findall(r"\((0x[0-9a-fA-F]+) - (\d+)\) << (\d+)", source):
        words_src.add(f"0x{(int(base, 16) - int(sub)) << int(sh):08x}")
    for n, line in enumerate(port.splitlines(), 1):
        code, _, comment = line.partition("#")
        for w in re.findall(r"0x[0-9A-Fa-f]{16}\b", code):
            cited = re.findall(r"0x1p(-?\d+)", comment)
            v = int(w, 16)
            if not cited or v != struct.unpack("<Q", struct.pack("<d", 2.0 ** int(cited[0])))[0]:
                fails.append(f"src/lgamma.cyr:{n}: {w} is not the power of two its comment cites")
        for w in re.findall(r"0x[0-9A-Fa-f]{8}\b", code):
            if w.lower() not in words_src:
                fails.append(f"src/lgamma.cyr:{n}: {w} does not occur in lgamma_r.rs")
    return fails


def main() -> int:
    paths = glob.glob(os.path.expanduser("~/.cargo/registry/src/*/" + SOURCE))
    if not paths:
        if CHECK:
            print(f"vendor_lgamma: unverified (no {SOURCE} in the cargo registry)")
            return 0
        sys.exit(f"cannot find {SOURCE} in the cargo registry (`cargo fetch` a crate that depends on libm 0.2.16)")
    raw = open(paths[0], "rb").read()
    if hashlib.sha256(raw).hexdigest() != SHA256:
        sys.exit(f"{paths[0]}: sha256 {hashlib.sha256(raw).hexdigest()[:16]}…, expected {SHA256[:16]}…")
    text = render(raw.decode("utf-8"))
    if CHECK:
        fails = [] if os.path.exists(OUT) and open(OUT, encoding="utf-8").read() == text else [
            "src/lgamma_data.cyr differs from what the source gives"]
        port = os.path.join(ROOT, "src", "lgamma.cyr")
        if os.path.exists(port):
            fails += inline_failures(open(port, encoding="utf-8").read(), raw.decode("utf-8"))
        for f in fails:
            print("FAILED:", f)
        print("vendor_lgamma: " + ("ok (libm 0.2.16 lgamma_r.rs; every inline word proven)" if not fails
                                   else f"{len(fails)} failures"))
        return 1 if fails else 0
    open(OUT, "w", encoding="utf-8").write(text)
    print(f"wrote src/lgamma_data.cyr ({text.count(chr(10))} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())

// p9_zeta_table.c — generate probe P9's double-double table of Euler's γ and ζ(k) (port plan §5 step 9d).
//
//   gcc -O2 -o build/p9/zeta scripts/probes/p9_zeta_table.c -lmpfr -lgmp
//   ./build/p9/zeta > scripts/probes/p9_zeta.cyr
//
// The series lnΓ(1 + a) = −γa + Σ (−1)^k ζ(k)/k·a^k and lnΓ(2 + y) = (1 − γ)y + Σ (−1)^k (ζ(k) − 1)/k·y^k (k ≥ 2)
// need these constants to double-double precision. MPFR computes each at 320 bits; hi = RN(v) and lo = RN(v − hi),
// both written as bit patterns, and the generator checks that hi + lo is within 2^-104 of v.
#include <stdio.h>
#include <string.h>
#include <stdint.h>
#include <stdlib.h>
#include <mpfr.h>

static uint64_t bits(double d) { uint64_t u; memcpy(&u, &d, 8); return u; }

// Splits v into hi + lo and checks the pair: |hi + lo − v| ≤ 2^-104·|v|.
static void split(mpfr_t v, double *hi, double *lo) {
    mpfr_t t, e;
    mpfr_inits2(320, t, e, (mpfr_ptr)0);
    *hi = mpfr_get_d(v, MPFR_RNDN);
    mpfr_sub_d(t, v, *hi, MPFR_RNDN);
    *lo = mpfr_get_d(t, MPFR_RNDN);
    mpfr_sub_d(e, t, *lo, MPFR_RNDN);
    mpfr_div(e, e, v, MPFR_RNDN);
    mpfr_abs(e, e, MPFR_RNDN);
    if (mpfr_cmp_d(e, 0x1p-104) > 0) { fprintf(stderr, "hi + lo misses by more than 2^-104\n"); exit(1); }
    mpfr_clears(t, e, (mpfr_ptr)0);
}

// One table, indexed by k (0 and 1 are 0): the hi or the lo parts, four words to a line.
static void table(const char *name, double *w) {
    printf("var _P9_Z_%s: i64[65] = {", name);
    for (int k = 0; k <= 64; k++)
        printf("%s0x%016lX%s", k % 4 ? " " : "\n    ", (unsigned long)bits(w[k]), k < 64 ? "," : "");
    printf("\n};\n");
}

int main(void) {
    mpfr_t v, one;
    mpfr_inits2(320, v, one, (mpfr_ptr)0);
    mpfr_set_ui(one, 1, MPFR_RNDN);
    static double zh[65], zl[65], mh[65], ml[65];
    double gh, gl;
    mpfr_const_euler(v, MPFR_RNDN);
    split(v, &gh, &gl);
    for (int k = 2; k <= 64; k++) {
        mpfr_zeta_ui(v, k, MPFR_RNDN);
        split(v, &zh[k], &zl[k]);
        mpfr_sub(v, v, one, MPFR_RNDN);
        split(v, &mh[k], &ml[k]);
    }
    printf("# p9_zeta.cyr — Euler's γ and ζ(k), k = 2 … 64, as double-doubles, for probe P9 (port plan §5 step 9d).\n");
    printf("#\n");
    printf("# GENERATED by scripts/probes/p9_zeta_table.c from MPFR %s at 320 bits. Do not edit. Each constant is a\n",
           mpfr_get_version());
    printf("# double-double, hi = RN(v) and lo = RN(v − hi), checked to 2^-104, held as bit patterns: γ as two\n");
    printf("# typed globals, ζ(k) (ZH, ZL) and ζ(k) − 1 (MH, ML, computed in MPFR before the split) as tables\n");
    printf("# indexed by k.\n\n");
    printf("var _P9_Z_EULER_H: f64 = 0x%016lX;   # %.17g\n", (unsigned long)bits(gh), gh);
    printf("var _P9_Z_EULER_L: f64 = 0x%016lX;\n", (unsigned long)bits(gl));
    table("ZH", zh);
    table("ZL", zl);
    table("MH", mh);
    table("ML", ml);
    mpfr_clears(v, one, (mpfr_ptr)0);
    return 0;
}

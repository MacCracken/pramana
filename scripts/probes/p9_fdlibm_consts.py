"""p9_fdlibm_consts.py — generate probe P9's fdlibm lgamma coefficients (port plan §5 step 9d).

    python3 -I -B scripts/probes/p9_fdlibm_consts.py > scripts/probes/p9_fdlibm_lgamma.cyr

Reads FreeBSD's e_lgamma_r.c as the libm crate 0.2.16 carries it (`src/math/lgamma_r.rs`, from the cargo registry)
and writes each `const NAME: f64` as a typed Cyrius global holding its bit pattern. Every constant is proven twice:
its decimal literal must parse to the bits in its hex comment, or the script fails. Constants are generated, never
typed by hand (CLAUDE.md).
"""

import glob
import os
import re
import struct
import sys

SOURCE = "libm-0.2.16/src/math/lgamma_r.rs"
LINE = re.compile(r"^const (\w+): f64 = ([-+0-9.eE]+); /\* (0x[0-9A-Fa-f]{8}), (0x[0-9A-Fa-f]{8}) \*/$")


def main() -> int:
    paths = glob.glob(os.path.expanduser("~/.cargo/registry/src/*/" + SOURCE))
    if not paths:
        sys.exit(f"cannot find {SOURCE} in the cargo registry")
    text = open(paths[0], encoding="utf-8").read()
    notice = text[: text.index("*/", text.index("Copyright")) + 2]
    out = []
    for line in text.splitlines():
        m = LINE.match(line.strip())
        if not m:
            continue
        name, dec, hi, lo = m.groups()
        bits = (int(hi, 16) << 32) | int(lo, 16)
        parsed = struct.unpack("<Q", struct.pack("<d", float(dec)))[0]
        if parsed != bits:
            sys.exit(f"{name}: {dec} parses to {parsed:016x}, the comment says {bits:016x}")
        out.append((name, bits, dec))
    if len(out) < 60:
        sys.exit(f"only {len(out)} constants found; the source changed")
    print("# p9_fdlibm_lgamma.cyr — fdlibm's lgamma coefficients for probe P9 (port plan §5 step 9d).")
    print("#")
    print("# GENERATED by scripts/probes/p9_fdlibm_consts.py from the libm crate 0.2.16's src/math/lgamma_r.rs,")
    print("# a transcription of FreeBSD's e_lgamma_r.c. Do not edit. Each value is a typed global holding its bit")
    print("# pattern, which the generator checked against the decimal literal. The source's notice, which its")
    print("# licence asks to keep:")
    print("#")
    for row in notice.splitlines():
        print(("# " + row).rstrip())
    print()
    for name, bits, dec in out:
        print(f"var _P9_LG_{name}: f64 = 0x{bits:016X};   # {dec}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

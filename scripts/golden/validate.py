class BayanRefusal(Exception):
    pass


def bayan_refusal(doc: bytes):
    """Why bayan 1.11.1 refuses a whole document that serde_json reads: a duplicate key in any object (keys compared
    decoded), nesting past 128 levels, or a lone surrogate escape in any string; None when there is none of these.
    Only meaningful on a document serde_json accepted, which is well formed."""
    b, n = doc, len(doc)
    pos = [0]

    def ws():
        while pos[0] < n and b[pos[0]] in JSON_WS:
            pos[0] += 1

    def hexval(at):
        return int(b[at:at + 4], 16)

    def string() -> bytes:
        pos[0] += 1
        out = bytearray()
        while True:
            c = b[pos[0]]
            pos[0] += 1
            if c == 0x22:
                return bytes(out)
            if c != 0x5C:
                out.append(c)
                continue
            e = b[pos[0]]
            pos[0] += 1
            if e != 0x75:
                out.append({0x62: 8, 0x66: 12, 0x6E: 10, 0x72: 13, 0x74: 9}.get(e, e))
                continue
            cp = hexval(pos[0])
            pos[0] += 4
            if 0xDC00 <= cp <= 0xDFFF:
                raise BayanRefusal("a lone low surrogate")
            if 0xD800 <= cp <= 0xDBFF:
                if b[pos[0]:pos[0] + 2] != b"\\u" or not 0xDC00 <= hexval(pos[0] + 2) <= 0xDFFF:
                    raise BayanRefusal("a lone high surrogate")
                cp = 0x10000 + ((cp - 0xD800) << 10) + (hexval(pos[0] + 2) - 0xDC00)
                pos[0] += 6
            out += chr(cp).encode("utf-8", "surrogatepass")

    def value(depth):
        ws()
        c = b[pos[0]]
        if c in (0x5B, 0x7B):
            if depth + 1 > 128:
                raise BayanRefusal("nesting past 128 levels")
            close = 0x5D if c == 0x5B else 0x7D
            pos[0] += 1
            keys = set()
            ws()
            if b[pos[0]] == close:
                pos[0] += 1
                return
            while True:
                if c == 0x7B:
                    ws()
                    key = string()
                    if key in keys:
                        raise BayanRefusal("a duplicate key")
                    keys.add(key)
                    ws()
                    pos[0] += 1                      # the colon
                value(depth + 1)
                ws()
                d = b[pos[0]]
                pos[0] += 1
                if d == close:
                    return
        elif c == 0x22:
            string()
        else:
            while pos[0] < n and b[pos[0]] not in b",]} \t\n\r":
                pos[0] += 1

    try:
        value(0)
    except BayanRefusal as r:
        return str(r)
    return None


def pct_bytes(x: bytes) -> str:
    return "".join(chr(c) if 0x21 <= c <= 0x7E and c != 0x25 else f"%{c:02X}" for c in x)


def serde_escape(x: bytes) -> bytes:
    """serde_json's format_escaped_str: quoted; `"` and `\\` escaped; \\b \\t \\n \\f \\r named; the other bytes
    below 0x20 as \\u00xx in lowercase hex; every other byte as it is."""
    named = {0x22: b'\\"', 0x5C: b"\\\\", 0x08: b"\\b", 0x09: b"\\t", 0x0A: b"\\n", 0x0C: b"\\f", 0x0D: b"\\r"}
    out = bytearray(b'"')
    for c in x:
        if c in named:
            out += named[c]
        elif c < 0x20:
            out += f"\\u{c:04x}".encode()
        else:
            out.append(c)
    return bytes(out + b'"')


def mvn_codec_value(toks):
    """A MultivariateNormal from the codec's and Debug's tokens (`v:d`, the mean, then the matrix's rows): the mean,
    the rows, hisab's factor and log det Σ through glibc's ln (1.3.0's). Raises when the correctly rounded ln gives
    another log det: the port's text would then differ from 1.3.0's (ADR 009), and the case should change."""
    d = int(next(toks)[len("v:"):])
    mean = [next(toks) for _ in range(d)]
    rows = []
    for _ in range(int(next(toks)[len("v:"):])):
        rows.append([next(toks) for _ in range(int(next(toks)[len("v:"):]))])
    lf = d_mvn_checks(d, mean, len(rows), d, [x for r in rows for x in r])
    if isinstance(lf, str) or any(len(r) != d for r in rows):
        raise ValueError("a MultivariateNormal case its constructor refuses")
    lg, lc = -0.0, -0.0
    for i in range(d):
        lg += _libm.log(lf[i * d + i])
        lc += mpfr_ref.cr("log", lf[i * d + i])
    if bits(lg * 2.0) != bits(lc * 2.0):
        raise ValueError(f"glibc's ln misrounds this case's log det ({lg * 2.0!r}): pick another")
    return mean, rows, [lf[i * d:(i + 1) * d] for i in range(d)], lg * 2.0


def mvn_json_accepts(*vals):
    """MultivariateNormalRepr's fields as tokens, then `MultivariateNormal::new`'s verdict (a finite log det included:
    a NaN pivot hisab keeps makes it NaN)."""
    it = iter(vals)
    d = int(next(it)[len("v:"):])
    mean = [next(it) for _ in range(d)]
    rows = []
    for _ in range(int(next(it)[len("v:"):])):
        rows.append([next(it) for _ in range(int(next(it)[len("v:"):]))])
    if d == 0 or not all(math.isfinite(v) for v in mean) or len(rows) != d or any(len(r) != d for r in rows):
        return False
    lf = d_mvn_checks(d, mean, d, d, [x for r in rows for x in r])
    if isinstance(lf, str):
        return False
    return all(lf[i * d + i] == lf[i * d + i] for i in range(d))


def serde_write(ty: str, toks) -> bytes:
    """serde_json::to_vec of the value whose golden tokens `toks` (an iterator) hold, for the shape ty."""
    if ty == "f64":
        return json_f64_text(next(toks)).encode()
    if ty in ("u64", "usize"):
        return str(next(toks) % (1 << 64)).encode()
    if ty == "bool":
        return b"true" if next(toks) else b"false"
    if ty == "String":
        return serde_escape(urllib.parse.unquote_to_bytes(next(toks)[len("s:"):]))
    if ty == "SimpleRng":
        seed = next(toks) % (1 << 64)
        return b'{"state":' + str(seed if seed != 0 else 1).encode() + b"}"
    if ty == "MultivariateNormal":
        mean, rows, lrows, ld = mvn_codec_value(toks)

        def vec(xs):
            return b"[" + b",".join(json_f64_text(x).encode() for x in xs) + b"]"

        return (b'{"mean":' + vec(mean) + b',"covariance":[' + b",".join(vec(r) for r in rows) + b'],"cholesky_l":['
                + b",".join(vec(r) for r in lrows) + b'],"log_det":' + json_f64_text(ld).encode() + b',"dim":'
                + str(len(mean)).encode() + b"}")
    if ty in JSON_STRUCTS or ty in JSON_VALIDATED:
        fields = JSON_STRUCTS[ty] if ty in JSON_STRUCTS else JSON_VALIDATED[ty][0]
        return b"{" + b",".join(b'"' + name.encode() + b'":' + serde_write(t, toks)
                                for name, t in fields) + b"}"
    if ty in JSON_ENUMS:
        name = next(toks).split(".", 1)[1].encode()
        return b'"' + name + b'"' if JSON_ENUMS[ty][1] is None else b'{"' + name + b'":""}'
    if ty.startswith("Vec<") and ty.endswith(">"):
        n = int(next(toks)[len("v:"):])
        return b"[" + b",".join(serde_write(ty[4:-1], toks) for _ in range(n)) + b"]"
    raise ValueError(f"no writer model for {ty}")


def serde_read(ty: str, doc: bytes):
    """serde_json::from_slice::<ty>(doc) as golden tokens: the value's, or ["E:Deserialize"]."""
    m = SerdeModel(doc)
    try:
        toks = m.value(ty)
        m.end()
        return toks
    except SerdeRefusal:
        return ["E:Deserialize"]


def check_json(rows):
    """The failures, the per-function counts, and the mapped rows: those serde_json reads only by skipping a member
    unchecked, which bayan refuses whole (ADR 007 row 16)."""
    failures, by_fn, mapped = [], {}, []
    for fn, _cls, ins, outs, raw in rows:
        stat = by_fn.setdefault(fn, [0, 0])
        if fn.startswith("json::write::"):
            got = urllib.parse.unquote_to_bytes(outs[0][len("s:"):])
            toks = iter(ins)
            want_text = serde_write(fn[len("json::write::"):], toks)
            ok = got == want_text and next(toks, None) is None and len(outs) == 1
            stat[0 if ok else 1] += 1
            if not ok:
                failures.append(f"json: {fn}{tuple(ins[:6])} recorded {got[:80]!r}, modelled {want_text[:80]!r}")
            continue
        code_only = fn == "json::PramanaError::code"
        ty = "PramanaError" if code_only else fn[len("json::"):]
        doc = urllib.parse.unquote_to_bytes(ins[0][len("s:"):])
        want = serde_read(ty, doc)
        if code_only and want != ["E:Deserialize"]:
            want = want[:1]                          # the codec keeps the variant (ADR 007 row 8)
        ok = len(want) == len(outs) and all(
            same(g, w) if isinstance(w, float) else g == w for g, w in zip(outs, want))
        stat[0 if ok else 1] += 1
        if not ok:
            failures.append(f"json: {fn}({doc[:80]!r}) recorded {outs[:6]}, modelled {want[:6]}")
        if want != ["E:Deserialize"]:
            why = bayan_refusal(doc)
            if why is not None:
                mapped.append(f"{fn}\t{raw}\tE:Deserialize\tserde_json reads it, skipping a member unchecked; bayan "
                              f"refuses the whole document: {why} (ADR 007 row 16)")
    return failures, by_fn, mapped



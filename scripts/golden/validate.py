"""validate.py — re-checks the golden corpus without the Rust oracle, and writes or checks the correctly rounded
rows (port plan M0 step 5, §3.5).

    python3 -I -B scripts/golden/validate.py .              # check everything; exit 1 on any failure
    python3 -I -B scripts/golden/validate.py . --write-cr   # (re)write tests/golden/*.cr.tsv, then check

Standard library plus ctypes: glibc's libm, and MPFR through `mpfr_ref.py`. It never runs the Rust oracle.
- **Format:** every generator file is parsed (header, row count, five fields, classes, tokens), and `modules.txt`
  must list exactly the generator's files.
- **`math`:**
  - every class-A/B row is recomputed in Python, in Rust's operation order;
  - every glibc class-C row is recomputed by calling the same glibc function through ctypes;
  - every `cbrt` row (compiler_builtins) is proven correctly rounded with MPFR.
- **`constants`:** every row is re-read from `rust-old/src` by this file's own extractor, a second implementation
  beside the generator's, with Python's float parser for the literals.
- **`math.cr.tsv`:** for every class-C row whose recorded value isn't correctly rounded, the correctly rounded value.
  This is the expectation the port's correctly rounded functions are gated against at 0 ulp (ADR 009). `--write-cr`
  writes it, and a plain run checks that the committed file is exactly what it would write.

A tampered row fails this check and the generator's `--check` alike.
"""

import ctypes
import importlib.util
import math
import re
import struct
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
_spec = importlib.util.spec_from_file_location("mpfr_ref", HERE / "mpfr_ref.py")
mpfr_ref = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(mpfr_ref)

MASK64 = (1 << 64) - 1
CLASSES = set("ABCDSR")
GEN_HEADER = "# pramana golden corpus, format 1: {}"
GEN_TAIL = ". Generated by scripts/golden; do not edit."
REGEN = "# regenerate: (cd scripts/golden && cargo run --release --locked)"
COLUMNS = "# columns: fn<TAB>class<TAB>inputs<TAB>outputs<TAB>note (tokens: scripts/golden/README.md)"


def bits(x: float) -> int:
    return struct.unpack("<Q", struct.pack("<d", x))[0]


def from_bits(b: int) -> float:
    return struct.unpack("<d", struct.pack("<Q", b & MASK64))[0]


def ordered(b: int) -> int:
    """f64 bits as a monotone integer: the ulp distance is a difference (+0 and −0 are 0 apart)."""
    return -(b & ((1 << 63) - 1)) if b & (1 << 63) else b


def same(a: float, b: float) -> bool:
    """Bit-identical, or both NaN (format 1: NaN matches any NaN)."""
    return (math.isnan(a) and math.isnan(b)) or bits(a) == bits(b)


# ── format ──


def parse_token(tok: str):
    kind, _, val = tok.partition(":")
    if kind == "f":
        if len(val) != 16:
            raise ValueError(f"bad f64 token {tok!r}")
        return from_bits(int(val, 16))
    if kind == "i":
        return int(val)
    if kind in ("e", "s", "E", "v") or tok == "n:":
        return tok
    raise ValueError(f"unknown token {tok!r}")


def parse_list(field: str):
    return [] if field == "-" else [parse_token(t) for t in field.split(" ")]


def read_module(path: Path, header0: str, tail: str):
    """(provenance line, rows) of a format-1 file; raises on any format error."""
    lines = path.read_text(encoding="utf-8").split("\n")
    if lines and lines[-1] == "":
        lines.pop()
    if len(lines) < 5:
        raise ValueError("short header")
    if lines[0] != header0:
        raise ValueError(f"header line 1 is {lines[0]!r}")
    if not (lines[1].startswith("# ") and lines[1].endswith(tail)):
        raise ValueError("header line 2 (provenance) malformed")
    if not lines[4].startswith("# rows: "):
        raise ValueError("header line 5 is not the row count")
    n = int(lines[4][len("# rows: "):])
    body = lines[5:]
    if n != len(body):
        raise ValueError(f"header says {n} rows, file has {len(body)}")
    rows = []
    for k, line in enumerate(body, start=6):
        parts = line.split("\t")
        if len(parts) != 5:
            raise ValueError(f"line {k}: {len(parts)} fields")
        fn, cls, ins, outs, _note = parts
        if cls not in CLASSES:
            raise ValueError(f"line {k}: class {cls!r}")
        rows.append((fn, cls, parse_list(ins), parse_list(outs), ins))
    return lines, rows


# ── constants: an independent reading of rust-old/src ──

STD_CONSTANTS = [  # (path, the spellings that name it, value)
    ("f64::EPSILON", ["f64::EPSILON"], sys.float_info.epsilon),
    ("f64::MIN_POSITIVE", ["f64::MIN_POSITIVE"], sys.float_info.min),
    ("f64::MAX", ["f64::MAX"], sys.float_info.max),
    ("f64::INFINITY", ["f64::INFINITY"], math.inf),
    ("f64::NEG_INFINITY", ["f64::NEG_INFINITY"], -math.inf),
    ("f64::NAN", ["f64::NAN"], math.nan),
    ("f64::consts::PI", ["consts::PI", "consts::{PI"], math.pi),
    ("f64::consts::E", ["consts::E"], math.e),
    ("f64::consts::TAU", ["consts::TAU"], math.tau),
    ("f64::consts::SQRT_2", ["SQRT_2"], math.sqrt(2.0)),
]


def library_part(text):
    k = text.rfind("#[cfg(test)]\nmod tests")
    return text if k < 0 else text[:k]


def rust_number(text, is_float):
    t = text.strip().replace("_", "")
    for suffix in ("f64", "usize", "u64"):
        if t.endswith(suffix) and not t[: -len(suffix)].endswith("e"):
            t = t[: -len(suffix)]
    return float(t) if is_float else int(t)


def enclosing(lines, at):
    ind = len(lines[at]) - len(lines[at].lstrip())
    if ind == 0:
        return None
    for line in reversed(lines[:at]):
        if not line.strip() or len(line) - len(line.lstrip()) >= ind:
            continue
        m = re.match(r"\s*(?:pub(?:\([a-z]+\))? )?(?:fn|mod) (\w+)", line)
        if m:
            return m.group(1)
    return None


def python_constants(root):
    """Every const in rust-old/src's library code, path → value, read by this file alone."""
    src = root / "rust-old" / "src"
    files = sorted((p.stem, p) for p in src.glob("*.rs"))
    files.append(("integration::soorat", src / "integration" / "soorat.rs"))
    files.sort()
    out, texts = {}, []
    for module, path in files:
        text = library_part(path.read_text(encoding="utf-8"))
        texts.append(text)
        lines = text.split("\n")
        scope_vals = {}
        k = 0
        while k < len(lines):
            m = re.match(r"\s*(?:pub(?:\([a-z]+\))? )?const (\w+): ([^=]+)= (.*)$", lines[k])
            if not m:
                k += 1
                continue
            name, ty, rhs = m.group(1), m.group(2).strip(), m.group(3).strip()
            scope = enclosing(lines, k)
            base = f"{module}::{scope}" if scope else module
            if ty.startswith("[f64;"):
                k += 1
                idx = 0
                while lines[k].strip() != "];":
                    out[f"{base}::{name}[{idx}]"] = rust_number(lines[k].strip().rstrip(","), True)
                    idx += 1
                    k += 1
                k += 1
                continue
            expr = rhs.rstrip(";")
            is_float = ty == "f64"
            if "<<" in expr:
                a, b = expr.split("<<")
                v = rust_number(a, False) << rust_number(b, False)
            elif " - " in expr:
                a, b = expr.split(" - ")
                v = rust_number(a, True) - scope_vals[b.strip()]
            else:
                v = rust_number(expr, is_float)
            scope_vals[name] = v
            out[f"{base}::{name}"] = v
            k += 1
    for path, spellings, v in STD_CONSTANTS:
        if any(re.search(re.escape(s) + r"(?![A-Za-z0-9_])", t) for s in spellings for t in texts):
            out[path] = v
    return out


def check_constants(root, rows):
    failures = []
    ours = python_constants(root)
    theirs = {}
    for fn, cls, ins, outs, _raw in rows:
        if fn != "const" or cls != "A" or len(ins) != 1 or not str(ins[0]).startswith("s:"):
            failures.append(f"constants: malformed row {fn} {cls} {ins}")
            continue
        path = re.sub(r"%([0-9A-F]{2})", lambda m: chr(int(m.group(1), 16)), ins[0][2:])
        theirs[path] = outs[0]
    for path in sorted(set(ours) ^ set(theirs)):
        where = "rust-old/src only" if path in ours else "constants.tsv only"
        failures.append(f"constants: {path} is in {where}")
    for path in sorted(set(ours) & set(theirs)):
        a, b = ours[path], theirs[path]
        ok = same(float(a), b) if isinstance(b, float) else (not isinstance(a, float) and a == b)
        if not ok:
            failures.append(f"constants: {path} is {a!r} in rust-old/src, {b!r} in constants.tsv")
    print(f"  {len(ours)} constants read independently from rust-old/src; "
          + ("all match" if not failures else f"{len(failures)} mismatches"))
    return failures


# ── math: class A / B in Python, in Rust's operation order ──


def r_sqrt(x):
    if math.isnan(x) or x == 0.0:
        return x
    return math.nan if x < 0 else math.sqrt(x)


def r_floor(x):
    if not math.isfinite(x) or x == 0.0:
        return x
    return float(math.floor(x))


def r_trunc(x):
    if not math.isfinite(x):
        return x
    return math.copysign(float(math.trunc(x)), x)


def r_fract(x):
    """Rust's `fract`: x − trunc(x)."""
    return x - r_trunc(x)


def r_maxmin(fn, x, y, recorded):
    """Rust's max / min (IEEE maxNum / minNum): a NaN operand yields the other. For ±0 against each other IEEE
    leaves the sign open, so the recorded value must be one of the two."""
    if math.isnan(x):
        return y
    if math.isnan(y):
        return x
    if x == y:
        return recorded if same(recorded, x) or same(recorded, y) else x
    if fn == "f64::max":
        return x if x > y else y
    return x if x < y else y


def r_clamp(x, lo, hi):
    if x < lo:
        x = lo
    if x > hi:
        x = hi
    return x


def total_key(x):
    s = bits(x)
    if s >= 1 << 63:
        s -= 1 << 64
    return s ^ 0x7FFF_FFFF_FFFF_FFFF if s < 0 else s


def r_as_usize(x):
    if math.isnan(x) or x < 0.0:
        return 0
    if x >= 18446744073709551616.0:
        return MASK64
    return int(x)


def to_i64(u):
    u &= MASK64
    return u - (1 << 64) if u >= 1 << 63 else u


def powi(x, n):
    """LLVM's square-and-multiply expansion of a literal powi: the result accumulates the set bits, low to high."""
    res, sq = None, x
    while n:
        if n & 1:
            res = sq if res is None else res * sq
        n >>= 1
        if n:
            sq = sq * sq
    return res


# ── math: class C from glibc (ctypes) and MPFR ──

_libm = ctypes.CDLL("libm.so.6")
GLIBC = {
    "f64::exp": "exp",
    "f64::ln": "log",
    "f64::ln_1p": "log1p",
    "f64::exp_m1": "expm1",
    "f64::sin": "sin",
    "f64::cos": "cos",
    "f64::tan": "tan",
    "f64::atan": "atan",
    "f64::log2": "log2",
}
for _name in list(GLIBC.values()) + ["pow"]:
    _fn = getattr(_libm, _name)
    _fn.restype = ctypes.c_double
    _fn.argtypes = [ctypes.c_double, ctypes.c_double] if _name == "pow" else [ctypes.c_double]
MPFR_NAME = dict(GLIBC, **{"f64::cbrt": "cbrt"})


def correctly_rounded(fn, ins):
    if fn == "f64::powf":
        return mpfr_ref.cr2("pow", ins[0], ins[1])
    return mpfr_ref.cr(MPFR_NAME[fn], ins[0])


def expected_math(fn, ins, outs):
    """What the row's output must be, recomputed without the oracle; None for a function this file doesn't know."""
    x = ins[0] if ins else None
    if fn == "f64::sqrt":
        return r_sqrt(x)
    if fn == "f64::abs":
        return math.fabs(x)
    if fn == "f64::floor":
        return r_floor(x)
    if fn == "f64::fract":
        return r_fract(x)
    if fn in ("f64::max", "f64::min"):
        return r_maxmin(fn, ins[0], ins[1], outs[0])
    if fn == "f64::clamp":
        return r_clamp(*ins)
    if fn == "f64::is_finite":
        return int(math.isfinite(x))
    if fn == "f64::is_nan":
        return int(math.isnan(x))
    if fn == "f64::total_cmp":
        a, b = total_key(ins[0]), total_key(ins[1])
        return (a > b) - (a < b)
    if fn == "f64::as_usize":
        return to_i64(r_as_usize(x))
    if fn == "u64::as_f64":
        return float(x & MASK64)
    if fn == "f64::high_word":
        return bits(x) >> 32
    if fn == "f64::low_masked":
        return from_bits(bits(x) & 0xFFFF_FFFF_0000_0000)
    if fn.startswith("f64::powi"):
        return powi(x, int(fn[len("f64::powi"):]))
    if fn == "f64::powf":
        return _libm.pow(ins[0], ins[1])
    if fn in GLIBC:
        return getattr(_libm, GLIBC[fn])(x)
    if fn == "f64::cbrt":
        return mpfr_ref.cr("cbrt", x)
    return None


def check_math(rows):
    failures, by_fn = [], {}
    for fn, cls, ins, outs, _raw in rows:
        want = expected_math(fn, ins, outs)
        stat = by_fn.setdefault(fn, [0, 0])
        if want is None:
            failures.append(f"math: no rule for {fn}")
            continue
        got = outs[0]
        ok = same(got, want) if isinstance(want, float) else got == want
        stat[0 if ok else 1] += 1
        if not ok:
            failures.append(f"math: {fn}{tuple(ins)} recorded {got!r}, recomputed {want!r}")
    return failures, by_fn


def cr_rows(rows):
    """The class-C rows whose recorded value isn't correctly rounded, with the correctly rounded value."""
    out = []
    for fn, cls, ins, outs, raw_ins in rows:
        if cls != "C":
            continue
        want = correctly_rounded(fn, ins)
        if same(outs[0], want):
            continue
        ulps = abs(ordered(bits(outs[0])) - ordered(bits(want)))
        note = (f"1.3.0 f:{bits(outs[0]):016x}; {fn}({', '.join(repr(v) for v in ins)}) glibc {outs[0]!r}, "
                f"{ulps} ulp off; correctly rounded {want!r}")
        out.append(f"{fn}\t{raw_ins}\tf:{bits(want):016x}\t{note}")
    return out


def render_cr(module, provenance, rows):
    """The siblings' correction format (pravash's, which tests/parity_core.cyr reads): four columns, the golden row's
    fn and inputs byte for byte as the key."""
    head = [
        f"# pramana correctly rounded rows (ADR 009), format 1: {module}",
        f"# recorded: {provenance}. Correctly rounded: MPFR {mpfr_ref.VERSION}. "
        "Generated by scripts/golden/validate.py; do not edit.",
        "# regenerate: python3 -I -B scripts/golden/validate.py . --write-cr",
        "# columns: fn<TAB>inputs<TAB>outputs<TAB>note (fn, inputs: the golden row's, byte for byte; outputs: Rust's "
        "operations with every primitive result correctly rounded)",
        f"# rows: {len(rows)}",
    ]
    return "\n".join(head + rows) + "\n"


def main(argv):
    root = Path(argv[1] if len(argv) > 1 else ".").resolve()
    write_cr = "--write-cr" in argv
    gdir = root / "tests" / "golden"
    failures = []

    names = sorted(p.name for p in gdir.glob("*.tsv")
                   if not p.name.endswith(".cr.tsv") and not p.name.endswith(".ref.tsv"))
    listed = [l for l in (gdir / "modules.txt").read_text(encoding="utf-8").splitlines() if not l.startswith("#")]
    if sorted(f"{m}.tsv" for m in listed) != names:
        failures.append(f"modules.txt lists {listed}, the directory has {names}")

    for name in names:
        module = name[: -len(".tsv")]
        try:
            lines, rows = read_module(gdir / name, GEN_HEADER.format(module), GEN_TAIL)
        except ValueError as e:
            failures.append(f"{name}: {e}")
            continue
        provenance = lines[1][len("# oracle: "): -len(GEN_TAIL)]
        print(f"{name}: {len(rows)} rows, format ok ({provenance})")
        if module == "constants":
            failures.extend(check_constants(root, rows))
        if module == "math":
            f, by_fn = check_math(rows)
            failures.extend(f)
            for fn in sorted(by_fn):
                ok, bad = by_fn[fn]
                print(f"  {fn:18s} {ok:6d} ok" + (f", {bad} FAILED" if bad else ""))
            crs = cr_rows(rows)
            text = render_cr(module, provenance, crs)
            cr_path = gdir / f"{module}.cr.tsv"
            if write_cr:
                cr_path.write_text(text, encoding="utf-8")
                print(f"  wrote {cr_path.name}: {len(crs)} rows")
            elif not cr_path.exists():
                failures.append(f"{cr_path.name} missing (run with --write-cr)")
            elif cr_path.read_text(encoding="utf-8") != text:
                failures.append(f"{cr_path.name} differs from what MPFR gives")
            else:
                print(f"  {cr_path.name}: {len(crs)} rows, as MPFR gives")
            per = {}
            for r in crs:
                per[r.split("\t", 1)[0]] = per.get(r.split("\t", 1)[0], 0) + 1
            total = {fn: sum(1 for row in rows if row[0] == fn) for fn in per}
            for fn in sorted(per):
                print(f"    {fn:18s} not correctly rounded on {per[fn]} of {total[fn]} rows")

    for msg in failures[:40]:
        print("FAILED:", msg)
    if len(failures) > 40:
        print(f"... and {len(failures) - 40} more")
    print("validate: " + ("ok" if not failures else f"{len(failures)} failures"))
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))

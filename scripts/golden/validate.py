def t1_ln_gamma(x):
    """src/lgamma.cyr's T1 lnΓ, as the port computes it."""
    u = bits(x)
    ix = (u >> 32) & 0x7FFFFFFF
    if ix >= 0x7FF00000:
        return x * x
    if ix < 0x3B900000:
        return -mpfr_ref.cr("log", abs(x))
    if x > 0.0:
        h, l = t_lg_pos_dd(x)
        return h + l
    a = -x
    if a >= 2.0 ** 52:
        return math.inf
    n = float(math.floor(a + 0.5))
    rr = a - n
    if rr == 0.0:
        return math.inf
    ar = abs(rr)
    qh, ql0 = t_two_prod(math.pi, ar)
    ql = ql0 + PI_L * ar
    sn = mpfr_ref.cr("sin", qh)
    cs = mpfr_ref.cr("cos", qh)
    lsh, lsl0 = mpfr_ref.ln_dd(sn)
    lsl = lsl0 + (ql * cs) / sn
    lah, lal = mpfr_ref.ln_dd(a)
    lph, lpl0 = mpfr_ref.ln_dd(math.pi)
    lpl = lpl0 + PI_L / math.pi
    gh, gl = t_lg_pos_dd(a)
    s1, e1 = t_two_sum(lph, -lah)
    s2, e2 = t_two_sum(s1, -lsh)
    s3, e3 = t_two_sum(s2, -gh)
    lo = ((e1 + e2) + e3) + (((lpl - lal) - lsl) - gl)
    return s3 + lo


# ── the T1 incomplete gamma (M2 part b4), as src/gammainc.cyr and src/dd.cyr compute it ──
# Every double-double step is the port's, in its order. kimiya's double-double ln core is MPFR's double-double of the

def library_part(text):
    k = text.rfind("#[cfg(test)]\nmod tests")
    return text if k < 0 else text[:k]


def rust_number(text, is_float):
    t = text.strip().replace("_", "")
    for suffix in ("f64", "usize", "u64"):
        if t.endswith(suffix) and not t[: -len(suffix)].endswith("e"):
            t = t[: -len(suffix)]
    return float(t) if is_float else int(t)


def enclosing(lines, at):
    ind = len(lines[at]) - len(lines[at].lstrip())
    if ind == 0:
        return None
    for line in reversed(lines[:at]):
        if not line.strip() or len(line) - len(line.lstrip()) >= ind:
            continue
        m = re.match(r"\s*(?:pub(?:\([a-z]+\))? )?(?:fn|mod) (\w+)", line)
        if m:
            return m.group(1)
    return None


def python_constants(root):
    """Every const in rust-old/src's library code, path → value, read by this file alone."""
    src = root / "rust-old" / "src"
    files = sorted((p.stem, p) for p in src.glob("*.rs"))
    files.append(("integration::soorat", src / "integration" / "soorat.rs"))
    files.sort()
    out, texts = {}, []
    for module, path in files:
        text = library_part(path.read_text(encoding="utf-8"))
        texts.append(text)
        lines = text.split("\n")
        scope_vals = {}
        k = 0
        while k < len(lines):
            m = re.match(r"\s*(?:pub(?:\([a-z]+\))? )?const (\w+): ([^=]+)= (.*)$", lines[k])
            if not m:
                k += 1
                continue
            name, ty, rhs = m.group(1), m.group(2).strip(), m.group(3).strip()
            scope = enclosing(lines, k)
            base = f"{module}::{scope}" if scope else module
            if ty.startswith("[f64;"):
                k += 1
                idx = 0
                while lines[k].strip() != "];":
                    out[f"{base}::{name}[{idx}]"] = rust_number(lines[k].strip().rstrip(","), True)
                    idx += 1
                    k += 1
                k += 1
                continue
            expr = rhs.rstrip(";")
            is_float = ty == "f64"
            if "<<" in expr:
                a, b = expr.split("<<")
                v = rust_number(a, False) << rust_number(b, False)
            elif " - " in expr:
                a, b = expr.split(" - ")
                v = rust_number(a, True) - scope_vals[b.strip()]
            else:
                v = rust_number(expr, is_float)
            scope_vals[name] = v
            out[f"{base}::{name}"] = v
            k += 1
    for path, spellings, v in STD_CONSTANTS:
        if any(re.search(re.escape(s) + r"(?![A-Za-z0-9_])", t) for s in spellings for t in texts):
            out[path] = v
    return out


def check_constants(root, rows):
    failures = []
    ours = python_constants(root)
    theirs = {}
    for fn, cls, ins, outs, _raw in rows:
        if fn != "const" or cls != "A" or len(ins) != 1 or not str(ins[0]).startswith("s:"):
            failures.append(f"constants: malformed row {fn} {cls} {ins}")
            continue
        path = re.sub(r"%([0-9A-F]{2})", lambda m: chr(int(m.group(1), 16)), ins[0][2:])
        theirs[path] = outs[0]
    for path in sorted(set(ours) ^ set(theirs)):
        where = "rust-old/src only" if path in ours else "constants.tsv only"
        failures.append(f"constants: {path} is in {where}")
    for path in sorted(set(ours) & set(theirs)):
        a, b = ours[path], theirs[path]
        ok = same(float(a), b) if isinstance(b, float) else (not isinstance(a, float) and a == b)
        if not ok:
            failures.append(f"constants: {path} is {a!r} in rust-old/src, {b!r} in constants.tsv")
    print(f"  {len(ours)} constants read independently from rust-old/src; "
          + ("all match" if not failures else f"{len(failures)} mismatches"))
    return failures


# ── math: class A / B in Python, in Rust's operation order ──


def r_sqrt(x):
    if math.isnan(x) or x == 0.0:
        return x
    return math.nan if x < 0 else math.sqrt(x)


def r_floor(x):
    if not math.isfinite(x) or x == 0.0:
        return x
    return float(math.floor(x))


def r_trunc(x):
    if not math.isfinite(x):
        return x
    return math.copysign(float(math.trunc(x)), x)


def r_fract(x):
    """Rust's `fract`: x − trunc(x)."""
    return x - r_trunc(x)


def r_maxmin(fn, x, y, recorded):
    """Rust's max / min (IEEE maxNum / minNum): a NaN operand yields the other. For ±0 against each other IEEE
    leaves the sign open, so the recorded value must be one of the two."""
    if math.isnan(x):
        return y
    if math.isnan(y):
        return x
    if x == y:
        return recorded if same(recorded, x) or same(recorded, y) else x
    if fn == "f64::max":
        return x if x > y else y
    return x if x < y else y


def r_clamp(x, lo, hi):
    if x < lo:
        x = lo
    if x > hi:
        x = hi
    return x


def total_key(x):
    s = bits(x)
    if s >= 1 << 63:
        s -= 1 << 64
    return s ^ 0x7FFF_FFFF_FFFF_FFFF if s < 0 else s


def r_as_usize(x):
    if math.isnan(x) or x < 0.0:
        return 0
    if x >= 18446744073709551616.0:
        return MASK64
    return int(x)


def to_i64(u):
    u &= MASK64
    return u - (1 << 64) if u >= 1 << 63 else u


def powi(x, n):
    """LLVM's square-and-multiply expansion of a literal powi: the result accumulates the set bits, low to high."""
    res, sq = None, x
    while n:
        if n & 1:
            res = sq if res is None else res * sq
        n >>= 1
        if n:
            sq = sq * sq
    return res


# ── math: class C from glibc (ctypes) and MPFR ──

_libm = ctypes.CDLL("libm.so.6")
GLIBC = {
    "f64::exp": "exp",
    "f64::ln": "log",
    "f64::ln_1p": "log1p",
    "f64::exp_m1": "expm1",
    "f64::sin": "sin",
    "f64::cos": "cos",
    "f64::tan": "tan",
    "f64::atan": "atan",
    "f64::log2": "log2",
}
for _name in list(GLIBC.values()) + ["pow"]:
    _fn = getattr(_libm, _name)
    _fn.restype = ctypes.c_double
    _fn.argtypes = [ctypes.c_double, ctypes.c_double] if _name == "pow" else [ctypes.c_double]
MPFR_NAME = dict(GLIBC, **{"f64::cbrt": "cbrt"})


def correctly_rounded(fn, ins):
    if fn == "f64::powf":
        return mpfr_ref.cr2("pow", ins[0], ins[1])
    return mpfr_ref.cr(MPFR_NAME[fn], ins[0])


def expected_math(fn, ins, outs):
    """What the row's output must be, recomputed without the oracle; None for a function this file doesn't know."""
    x = ins[0] if ins else None
    if fn == "f64::sqrt":
        return r_sqrt(x)
    if fn == "f64::abs":
        return math.fabs(x)
    if fn == "f64::floor":
        return r_floor(x)
    if fn == "f64::fract":
        return r_fract(x)
    if fn in ("f64::max", "f64::min"):
        return r_maxmin(fn, ins[0], ins[1], outs[0])
    if fn == "f64::clamp":
        return r_clamp(*ins)
    if fn == "f64::is_finite":
        return int(math.isfinite(x))
    if fn == "f64::is_nan":
        return int(math.isnan(x))
    if fn == "f64::total_cmp":
        a, b = total_key(ins[0]), total_key(ins[1])
        return (a > b) - (a < b)
    if fn == "f64::as_usize":
        return to_i64(r_as_usize(x))
    if fn == "u64::as_f64":
        return float(x & MASK64)
    if fn == "f64::high_word":
        return bits(x) >> 32
    if fn == "f64::low_masked":
        return from_bits(bits(x) & 0xFFFF_FFFF_0000_0000)
    if fn.startswith("f64::powi"):
        return powi(x, int(fn[len("f64::powi"):]))
    if fn == "f64::powf":
        return _libm.pow(ins[0], ins[1])
    if fn in GLIBC:
        return getattr(_libm, GLIBC[fn])(x)
    if fn == "f64::cbrt":
        return mpfr_ref.cr("cbrt", x)
    return None


# ── fmt: serde_json's f64 text, from Python's shortest digits ──


def json_f64_text(x: float) -> str:
    """serde_json 1.0.154's text for x: positional for decimal exponents −5 … 15 (".0" on an integer), otherwise
    d.ddde±x; `null` for NaN and ±∞. The digits are Python's repr's, normalised to 0.D × 10^k."""
    if math.isnan(x) or math.isinf(x):
        return "null"
    sign = "-" if math.copysign(1.0, x) < 0 else ""
    if x == 0.0:
        return sign + "0.0"
    d = Decimal(repr(abs(x))).normalize()
    _, digit_tuple, exp = d.as_tuple()
    digits = "".join(str(t) for t in digit_tuple)
    n = len(digits)
    k = n + exp
    ex = k - 1
    if -5 <= ex <= 15:
        if k <= 0:
            body = "0." + "0" * (-k) + digits
        elif k >= n:
            body = digits + "0" * (k - n) + ".0"
        else:
            body = digits[:k] + "." + digits[k:]
    else:
        body = digits[0] + ("." + digits[1:] if n > 1 else "") + "e" + ("+" if ex >= 0 else "-") + str(abs(ex))
    return sign + body


def check_fmt(rows):
    failures, ok = [], 0
    for fn, _cls, ins, outs, _raw in rows:
        if fn != "f64::to_json":
            failures.append(f"fmt: no rule for {fn}")
            continue
        got = urllib.parse.unquote(outs[0][len("s:"):])
        want = json_f64_text(ins[0])
        if got == want:
            ok += 1
        else:
            failures.append(f"fmt: {fn}({ins[0]!r}) recorded {got!r}, recomputed {want!r}")
    return failures, ok


# ── json: serde_json 1.0.154's reading, modelled from its source (de.rs, read.rs) ──


class SerdeRefusal(Exception):
    pass


JSON_WS = b" \t\n\r"
U64_MAX = (1 << 64) - 1


class SerdeModel:
    """serde_json's from_slice for one document: the strict RFC 8259 grammar, whitespace = space, tab, LF, CR, and
    serde's rules for each value type (`float_roundtrip`: every float correctly rounded)."""

    def __init__(self, doc: bytes):
        self.b, self.i = doc, 0

    def peek(self):
        return self.b[self.i] if self.i < len(self.b) else None

    def ws(self):
        while self.i < len(self.b) and self.b[self.i] in JSON_WS:
            self.i += 1

    def expect(self, lit: bytes):
        if self.b[self.i:self.i + len(lit)] != lit:
            raise SerdeRefusal("expected " + lit.decode())
        self.i += len(lit)

    def end(self):
        self.ws()
        if self.i != len(self.b):
            raise SerdeRefusal("trailing characters")

    def number(self):
        """('u', int), ('i', int) or ('f', float) as serde_json's ParserNumber, or a refusal."""
        text, neg, is_float = self.number_text()
        if not is_float:
            mag = int(text.lstrip("-"))
            if not neg and mag <= U64_MAX:
                return ("u", mag)
            if neg and mag == 0:
                return ("f", -0.0)                   # parse_integer: -0 is the float -0.0
            if neg and mag <= 1 << 63:
                return ("i", -mag)
            try:
                return ("f", float(-mag if neg else mag))
            except OverflowError:
                raise SerdeRefusal("number out of range")
        x = float(text)
        if math.isinf(x):
            raise SerdeRefusal("number out of range")
        return ("f", x)

    def number_text(self):
        """The strict number grammar alone (ignore_integer's too): (text, negative, has a fraction or exponent)."""
        st = self.i
        neg = self.peek() == 0x2D
        if neg:
            self.i += 1
        c = self.peek()
        if c == 0x30:
            self.i += 1
            if self.peek() is not None and 0x30 <= self.peek() <= 0x39:
                raise SerdeRefusal("leading zero")
        elif c is not None and 0x31 <= c <= 0x39:
            while self.peek() is not None and 0x30 <= self.peek() <= 0x39:
                self.i += 1
        else:
            raise SerdeRefusal("invalid number")
        is_float = False
        if self.peek() == 0x2E:
            is_float = True
            self.i += 1
            if not (self.peek() is not None and 0x30 <= self.peek() <= 0x39):
                raise SerdeRefusal("no digit after the point")
            while self.peek() is not None and 0x30 <= self.peek() <= 0x39:
                self.i += 1
        if self.peek() in (0x65, 0x45):
            is_float = True
            self.i += 1
            if self.peek() in (0x2B, 0x2D):
                self.i += 1
            if not (self.peek() is not None and 0x30 <= self.peek() <= 0x39):
                raise SerdeRefusal("no exponent digit")
            while self.peek() is not None and 0x30 <= self.peek() <= 0x39:
                self.i += 1
        return self.b[st:self.i].decode("ascii"), neg, is_float

    def string(self) -> bytes:
        """parse_str with validation: escapes decoded, surrogates paired, control bytes refused, UTF-8 checked."""
        if self.peek() != 0x22:
            raise SerdeRefusal("expected a string")
        self.i += 1
        out = bytearray()
        while True:
            c = self.peek()
            if c is None:
                raise SerdeRefusal("EOF in a string")
            self.i += 1
            if c == 0x22:
                break
            if c < 0x20:
                raise SerdeRefusal("control character in a string")
            if c != 0x5C:
                out.append(c)
                continue
            e = self.peek()
            if e is None:
                raise SerdeRefusal("EOF in an escape")
            self.i += 1
            simple = {0x22: 0x22, 0x5C: 0x5C, 0x2F: 0x2F, 0x62: 8, 0x66: 12, 0x6E: 10, 0x72: 13, 0x74: 9}
            if e in simple:
                out.append(simple[e])
                continue
            if e != 0x75:
                raise SerdeRefusal("invalid escape")
            cp = self.hex4()
            if 0xDC00 <= cp <= 0xDFFF:
                raise SerdeRefusal("lone trailing surrogate")
            if 0xD800 <= cp <= 0xDBFF:
                if self.b[self.i:self.i + 2] != b"\\u":
                    raise SerdeRefusal("lone leading surrogate")
                self.i += 2
                lo = self.hex4()
                if not 0xDC00 <= lo <= 0xDFFF:
                    raise SerdeRefusal("lone leading surrogate")
                cp = 0x10000 + ((cp - 0xD800) << 10) + (lo - 0xDC00)
            out += chr(cp).encode("utf-8")
        try:
            out.decode("utf-8")
        except UnicodeDecodeError:
            raise SerdeRefusal("invalid UTF-8")
        return bytes(out)

    def ignore_str(self):
        """ignore_str, after the opening quote: control bytes and malformed escapes refuse; nothing else is checked
        (no UTF-8, no surrogate pairing)."""
        while True:
            c = self.peek()
            if c is None:
                raise SerdeRefusal("EOF in a string")
            self.i += 1
            if c == 0x22:
                return
            if c < 0x20:
                raise SerdeRefusal("control character in a string")
            if c == 0x5C:
                e = self.peek()
                if e is None:
                    raise SerdeRefusal("EOF in an escape")
                self.i += 1
                if e == 0x75:
                    self.hex4()
                elif e not in b'"\\/bfnrt':
                    raise SerdeRefusal("invalid escape")

    def ignore_value(self):
        """ignore_value: any JSON value, checked for syntax only, nested without a depth limit."""
        self.ws()
        c = self.peek()
        if c == 0x6E:
            self.expect(b"null")
        elif c == 0x74:
            self.expect(b"true")
        elif c == 0x66:
            self.expect(b"false")
        elif c is not None and (c == 0x2D or 0x30 <= c <= 0x39):
            self.number_text()
        elif c == 0x22:
            self.i += 1
            self.ignore_str()
        elif c in (0x5B, 0x7B):
            close = 0x5D if c == 0x5B else 0x7D
            self.i += 1
            self.ws()
            if self.peek() == close:
                self.i += 1
                return
            while True:
                if c == 0x7B:
                    self.ws()
                    if self.peek() != 0x22:
                        raise SerdeRefusal("key must be a string")
                    self.i += 1
                    self.ignore_str()
                    self.ws()
                    if self.peek() != 0x3A:
                        raise SerdeRefusal("expected a colon")
                    self.i += 1
                self.ignore_value()
                self.ws()
                d = self.peek()
                if d == close:
                    self.i += 1
                    return
                if d != 0x2C:
                    raise SerdeRefusal("expected , or a close")
                self.i += 1
        else:
            raise SerdeRefusal("expected a value")

    def struct(self, fields):
        """serde derive's visit_map and visit_seq through deserialize_struct."""
        self.ws()
        c = self.peek()
        if c == 0x5B:
            self.i += 1
            parts = []
            for k, (_name, ty) in enumerate(fields):
                self.ws()
                c = self.peek()
                if c is None or c == 0x5D:
                    raise SerdeRefusal("invalid length")
                if k > 0:
                    if c != 0x2C:
                        raise SerdeRefusal("expected , or ]")
                    self.i += 1
                    self.ws()
                    if self.peek() == 0x5D:
                        raise SerdeRefusal("trailing comma")
                parts.append(self.value(ty))
            self.ws()
            if self.peek() != 0x5D:
                raise SerdeRefusal("trailing characters in the sequence")
            self.i += 1
            return [t for part in parts for t in part]
        if c != 0x7B:
            raise SerdeRefusal("invalid type")
        self.i += 1
        got, first = {}, True
        names = {name.encode(): (name, ty) for name, ty in fields}
        while True:
            self.ws()
            c = self.peek()
            if c is None:
                raise SerdeRefusal("EOF in an object")
            if c == 0x7D and first:
                self.i += 1
                break
            if not first:
                if c == 0x7D:
                    self.i += 1
                    break
                if c != 0x2C:
                    raise SerdeRefusal("expected , or }")
                self.i += 1
                self.ws()
                c = self.peek()
            if c != 0x22:
                raise SerdeRefusal("key must be a string (or a trailing comma)")
            first = False
            key = self.string()                      # a struct's keys are parsed, the unknown ones too
            self.ws()
            if self.peek() != 0x3A:
                raise SerdeRefusal("expected a colon")
            self.i += 1
            if key in names:
                if key in got:
                    raise SerdeRefusal("duplicate field")
                got[key] = self.value(names[key][1])
            else:
                self.ignore_value()
        for name, _ty in fields:
            if name.encode() not in got:
                raise SerdeRefusal("missing field")
        return [t for name, _ty in fields for t in got[name.encode()]]

    def enum(self, enum_name, variants, payload):
        """An externally tagged enum: unit variants (payload None) or newtype variants holding `payload`."""
        self.ws()
        c = self.peek()
        if c == 0x22:
            name = self.string()
            if payload is not None or name.decode("utf-8") not in variants:
                raise SerdeRefusal("unknown variant, or a unit variant for a newtype")
            return [f"e:{enum_name}.{name.decode()}"]
        if c != 0x7B:
            raise SerdeRefusal("expected an enum")
        self.i += 1
        self.ws()
        if self.peek() != 0x22:
            raise SerdeRefusal("expected the variant")
        name = self.string()
        if name.decode("utf-8") not in variants:
            raise SerdeRefusal("unknown variant")
        self.ws()
        if self.peek() != 0x3A:
            raise SerdeRefusal("expected a colon")
        self.i += 1
        if payload is None:
            self.ws()
            self.expect(b"null")
            toks = []
        else:
            toks = self.value(payload)
        self.ws()
        if self.peek() != 0x7D:
            raise SerdeRefusal("expected }")
        self.i += 1
        return [f"e:{enum_name}.{name.decode()}"] + toks

    def hex4(self) -> int:
        h = self.b[self.i:self.i + 4]
        if len(h) < 4 or any(chr(x) not in "0123456789abcdefABCDEF" for x in h):
            raise SerdeRefusal("invalid hex escape")
        self.i += 4
        return int(h, 16)

    def value(self, ty: str):
        """The tokens serde's Deserialize for `ty` reads at the cursor."""
        self.ws()
        c = self.peek()
        if ty in ("f64", "u64", "usize"):
            if c is None or not (c == 0x2D or 0x30 <= c <= 0x39):
                raise SerdeRefusal("invalid type")
            kind, v = self.number()
            if ty == "f64":
                return [float(v)]                    # u64 and i64 convert as Rust's `as f64`: correctly rounded
            if kind != "u":
                raise SerdeRefusal("invalid type or value")
            return [v - (1 << 64) if v >= 1 << 63 else v]
        if ty == "bool":
            if c == 0x74:
                self.expect(b"true")
                return [1]
            if c == 0x66:
                self.expect(b"false")
                return [0]
            raise SerdeRefusal("invalid type")
        if ty == "String":
            return ["s:" + pct_bytes(self.string())]
        if ty in JSON_STRUCTS:
            return self.struct(JSON_STRUCTS[ty])
        if ty in JSON_ENUMS:
            return self.enum(ty, *JSON_ENUMS[ty])
        if ty.startswith("Vec<") and ty.endswith(">"):
            inner = ty[4:-1]
            if c != 0x5B:
                raise SerdeRefusal("invalid type")
            self.i += 1
            elems = []
            self.ws()
            if self.peek() == 0x5D:
                self.i += 1
                return [f"v:0"]
            while True:
                elems.append(self.value(inner))
                self.ws()
                c = self.peek()
                if c == 0x2C:
                    self.i += 1
                    self.ws()
                    if self.peek() == 0x5D:
                        raise SerdeRefusal("trailing comma")
                    continue
                if c == 0x5D:
                    self.i += 1
                    break
                raise SerdeRefusal("expected , or ]")
            return [f"v:{len(elems)}"] + [t for e in elems for t in e]
        raise ValueError(f"no model for {ty}")


# The generator's test structs and 1.3.0's two enums (scripts/golden/src/m_json.rs).
JSON_STRUCTS = {
    "Pair": [("mean", "f64"), ("std_dev", "f64")],
    "Shapes": [("x", "f64"), ("n", "u64"), ("k", "usize"), ("flag", "bool"), ("name", "String"), ("xs", "Vec<f64>"),
               ("ns", "Vec<u64>"), ("labels", "Vec<String>"), ("m", "Vec<Vec<f64>>"), ("kernel", "Kernel")],
}
JSON_ENUMS = {
    "Kernel": (["Gaussian", "Epanechnikov", "Uniform", "Triangular"], None),
    "PramanaError": (["InvalidParameter", "InvalidSample", "ConvergenceFailure", "DimensionMismatch",
                      "ComputationError"], "String"),
}


class BayanRefusal(Exception):
    pass


def bayan_refusal(doc: bytes):
    """Why bayan 1.11.1 refuses a whole document that serde_json reads: a duplicate key in any object (keys compared
    decoded), nesting past 128 levels, or a lone surrogate escape in any string; None when there is none of these.
    Only meaningful on a document serde_json accepted, which is well formed."""
    b, n = doc, len(doc)
    pos = [0]

    def ws():
        while pos[0] < n and b[pos[0]] in JSON_WS:
            pos[0] += 1

    def hexval(at):
        return int(b[at:at + 4], 16)

    def string() -> bytes:
        pos[0] += 1
        out = bytearray()
        while True:
            c = b[pos[0]]
            pos[0] += 1
            if c == 0x22:
                return bytes(out)
            if c != 0x5C:
                out.append(c)
                continue
            e = b[pos[0]]
            pos[0] += 1
            if e != 0x75:
                out.append({0x62: 8, 0x66: 12, 0x6E: 10, 0x72: 13, 0x74: 9}.get(e, e))
                continue
            cp = hexval(pos[0])
            pos[0] += 4
            if 0xDC00 <= cp <= 0xDFFF:
                raise BayanRefusal("a lone low surrogate")
            if 0xD800 <= cp <= 0xDBFF:
                if b[pos[0]:pos[0] + 2] != b"\\u" or not 0xDC00 <= hexval(pos[0] + 2) <= 0xDFFF:
                    raise BayanRefusal("a lone high surrogate")
                cp = 0x10000 + ((cp - 0xD800) << 10) + (hexval(pos[0] + 2) - 0xDC00)
                pos[0] += 6
            out += chr(cp).encode("utf-8", "surrogatepass")

    def value(depth):
        ws()
        c = b[pos[0]]
        if c in (0x5B, 0x7B):
            if depth + 1 > 128:
                raise BayanRefusal("nesting past 128 levels")
            close = 0x5D if c == 0x5B else 0x7D
            pos[0] += 1
            keys = set()
            ws()
            if b[pos[0]] == close:
                pos[0] += 1
                return
            while True:
                if c == 0x7B:
                    ws()
                    key = string()
                    if key in keys:
                        raise BayanRefusal("a duplicate key")
                    keys.add(key)
                    ws()
                    pos[0] += 1                      # the colon
                value(depth + 1)
                ws()
                d = b[pos[0]]
                pos[0] += 1
                if d == close:
                    return
        elif c == 0x22:
            string()
        else:
            while pos[0] < n and b[pos[0]] not in b",]} \t\n\r":
                pos[0] += 1

    try:
        value(0)
    except BayanRefusal as r:
        return str(r)
    return None


def pct_bytes(x: bytes) -> str:
    return "".join(chr(c) if 0x21 <= c <= 0x7E and c != 0x25 else f"%{c:02X}" for c in x)


def serde_escape(x: bytes) -> bytes:
    """serde_json's format_escaped_str: quoted; `"` and `\\` escaped; \\b \\t \\n \\f \\r named; the other bytes
    below 0x20 as \\u00xx in lowercase hex; every other byte as it is."""
    named = {0x22: b'\\"', 0x5C: b"\\\\", 0x08: b"\\b", 0x09: b"\\t", 0x0A: b"\\n", 0x0C: b"\\f", 0x0D: b"\\r"}
    out = bytearray(b'"')
    for c in x:
        if c in named:
            out += named[c]
        elif c < 0x20:
            out += f"\\u{c:04x}".encode()
        else:
            out.append(c)
    return bytes(out + b'"')


def serde_write(ty: str, toks) -> bytes:
    """serde_json::to_vec of the value whose golden tokens `toks` (an iterator) hold, for the shape ty."""
    if ty == "f64":
        return json_f64_text(next(toks)).encode()
    if ty in ("u64", "usize"):
        return str(next(toks) % (1 << 64)).encode()
    if ty == "bool":
        return b"true" if next(toks) else b"false"
    if ty == "String":
        return serde_escape(urllib.parse.unquote_to_bytes(next(toks)[len("s:"):]))
    if ty in JSON_STRUCTS:
        return b"{" + b",".join(b'"' + name.encode() + b'":' + serde_write(t, toks)
                                for name, t in JSON_STRUCTS[ty]) + b"}"
    if ty in JSON_ENUMS:
        name = next(toks).split(".", 1)[1].encode()
        return b'"' + name + b'"' if JSON_ENUMS[ty][1] is None else b'{"' + name + b'":""}'
    if ty.startswith("Vec<") and ty.endswith(">"):
        n = int(next(toks)[len("v:"):])
        return b"[" + b",".join(serde_write(ty[4:-1], toks) for _ in range(n)) + b"]"
    raise ValueError(f"no writer model for {ty}")


def serde_read(ty: str, doc: bytes):
    """serde_json::from_slice::<ty>(doc) as golden tokens: the value's, or ["E:Deserialize"]."""
    m = SerdeModel(doc)
    try:
        toks = m.value(ty)
        m.end()
        return toks
    except SerdeRefusal:
        return ["E:Deserialize"]


def check_json(rows):
    """The failures, the per-function counts, and the mapped rows: those serde_json reads only by skipping a member
    unchecked, which bayan refuses whole (ADR 007 row 16)."""
    failures, by_fn, mapped = [], {}, []
    for fn, _cls, ins, outs, raw in rows:
        stat = by_fn.setdefault(fn, [0, 0])
        if fn.startswith("json::write::"):
            got = urllib.parse.unquote_to_bytes(outs[0][len("s:"):])
            toks = iter(ins)
            want_text = serde_write(fn[len("json::write::"):], toks)
            ok = got == want_text and next(toks, None) is None and len(outs) == 1
            stat[0 if ok else 1] += 1
            if not ok:
                failures.append(f"json: {fn}{tuple(ins[:6])} recorded {got[:80]!r}, modelled {want_text[:80]!r}")
            continue
        code_only = fn == "json::PramanaError::code"
        ty = "PramanaError" if code_only else fn[len("json::"):]
        doc = urllib.parse.unquote_to_bytes(ins[0][len("s:"):])
        want = serde_read(ty, doc)
        if code_only and want != ["E:Deserialize"]:
            want = want[:1]                          # the codec keeps the variant (ADR 007 row 8)
        ok = len(want) == len(outs) and all(
            same(g, w) if isinstance(w, float) else g == w for g, w in zip(outs, want))
        stat[0 if ok else 1] += 1
        if not ok:
            failures.append(f"json: {fn}({doc[:80]!r}) recorded {outs[:6]}, modelled {want[:6]}")
        if want != ["E:Deserialize"]:
            why = bayan_refusal(doc)
            if why is not None:
                mapped.append(f"{fn}\t{raw}\tE:Deserialize\tserde_json reads it, skipping a member unchecked; bayan "
                              f"refuses the whole document: {why} (ADR 007 row 16)")
    return failures, by_fn, mapped


def render_map(module, provenance, rows):
    """The mapped rows (ADR 007), in the correction format tests/parity_core.cyr reads, keyed by the golden row's fn
    and inputs byte for byte."""
    head = [
        f"# pramana mapped rows (ADR 007), format 1: {module}",
        f"# recorded: {provenance}. Mapped by ADR 007 row 16. Generated by scripts/golden/validate.py; do not edit.",
        "# regenerate: python3 -I -B scripts/golden/validate.py . --write-cr",
        "# columns: fn<TAB>inputs<TAB>outputs<TAB>note (fn, inputs: the golden row's, byte for byte; outputs: pramana's, "
        "under the ADR)",
        f"# rows: {len(rows)}",
    ]
    return "\n".join(head + rows) + "\n"


def check_math(rows):
    failures, by_fn = [], {}
    for fn, cls, ins, outs, _raw in rows:
        want = expected_math(fn, ins, outs)
        stat = by_fn.setdefault(fn, [0, 0])
        if want is None:
            failures.append(f"math: no rule for {fn}")
            continue
        got = outs[0]
        ok = same(got, want) if isinstance(want, float) else got == want
        stat[0 if ok else 1] += 1
        if not ok:
            failures.append(f"math: {fn}{tuple(ins)} recorded {got!r}, recomputed {want!r}")
    return failures, by_fn


def cr_rows(rows):
    """The class-C rows whose recorded value isn't correctly rounded, with the correctly rounded value."""
    out = []
    for fn, cls, ins, outs, raw_ins in rows:
        if cls != "C":
            continue
        want = correctly_rounded(fn, ins)
        if same(outs[0], want):
            continue
        ulps = abs(ordered(bits(outs[0])) - ordered(bits(want)))
        note = (f"1.3.0 f:{bits(outs[0]):016x}; {fn}({', '.join(repr(v) for v in ins)}) glibc {outs[0]!r}, "
                f"{ulps} ulp off; correctly rounded {want!r}")
        out.append(f"{fn}\t{raw_ins}\tf:{bits(want):016x}\t{note}")
    return out


def render_cr(module, provenance, rows):
    """The siblings' correction format (pravash's, which tests/parity_core.cyr reads): four columns, the golden row's
    fn and inputs byte for byte as the key."""
    head = [
        f"# pramana correctly rounded rows (ADR 009), format 1: {module}",
        f"# recorded: {provenance}. Correctly rounded: MPFR {mpfr_ref.VERSION}. "
        "Generated by scripts/golden/validate.py; do not edit.",
        "# regenerate: python3 -I -B scripts/golden/validate.py . --write-cr",
        "# columns: fn<TAB>inputs<TAB>outputs<TAB>note (fn, inputs: the golden row's, byte for byte; outputs: Rust's "
        "operations with every primitive result correctly rounded)",
        f"# rows: {len(rows)}",
    ]
    return "\n".join(head + rows) + "\n"


def main(argv):
    root = Path(argv[1] if len(argv) > 1 else ".").resolve()
    write_cr = "--write-cr" in argv
    gdir = root / "tests" / "golden"
    failures = []

    names = sorted(p.name for p in gdir.glob("*.tsv")
                   if not p.name.endswith((".cr.tsv", ".ref.tsv", ".map.tsv")))
    listed = [l for l in (gdir / "modules.txt").read_text(encoding="utf-8").splitlines() if not l.startswith("#")]
    if sorted(f"{m}.tsv" for m in listed) != names:
        failures.append(f"modules.txt lists {listed}, the directory has {names}")

    for name in names:
        module = name[: -len(".tsv")]
        try:
            lines, rows = read_module(gdir / name, GEN_HEADER.format(module), GEN_TAIL)
        except ValueError as e:
            failures.append(f"{name}: {e}")
            continue
        provenance = lines[1][len("# oracle: "): -len(GEN_TAIL)]
        print(f"{name}: {len(rows)} rows, format ok ({provenance})")
        if module == "constants":
            failures.extend(check_constants(root, rows))
        if module == "fmt":
            f, ok = check_fmt(rows)
            failures.extend(f)
            print(f"  f64::to_json {ok:6d} ok" + (f", {len(f)} FAILED" if f else ""))
        if module == "json":
            f, by_fn, mapped = check_json(rows)
            failures.extend(f)
            for fn in sorted(by_fn):
                ok, bad = by_fn[fn]
                print(f"  {fn:28s} {ok:6d} ok" + (f", {bad} FAILED" if bad else ""))
            text = render_map(module, provenance, mapped)
            map_path = gdir / f"{module}.map.tsv"
            if write_cr:
                map_path.write_text(text, encoding="utf-8")
                print(f"  wrote {map_path.name}: {len(mapped)} rows")
            elif not map_path.exists():
                failures.append(f"{map_path.name} missing (run with --write-cr)")
            elif map_path.read_text(encoding="utf-8") != text:
                failures.append(f"{map_path.name} differs from what the bayan model gives")
            else:
                print(f"  {map_path.name}: {len(mapped)} rows, as the bayan model gives")
        if module == "math":
            f, by_fn = check_math(rows)
            failures.extend(f)
            for fn in sorted(by_fn):
                ok, bad = by_fn[fn]
                print(f"  {fn:18s} {ok:6d} ok" + (f", {bad} FAILED" if bad else ""))
            crs = cr_rows(rows)
            text = render_cr(module, provenance, crs)
            cr_path = gdir / f"{module}.cr.tsv"
            if write_cr:
                cr_path.write_text(text, encoding="utf-8")
                print(f"  wrote {cr_path.name}: {len(crs)} rows")
            elif not cr_path.exists():
                failures.append(f"{cr_path.name} missing (run with --write-cr)")
            elif cr_path.read_text(encoding="utf-8") != text:
                failures.append(f"{cr_path.name} differs from what MPFR gives")
            else:
                print(f"  {cr_path.name}: {len(crs)} rows, as MPFR gives")
            per = {}
            for r in crs:
                per[r.split("\t", 1)[0]] = per.get(r.split("\t", 1)[0], 0) + 1
            total = {fn: sum(1 for row in rows if row[0] == fn) for fn in per}
            for fn in sorted(per):
                print(f"    {fn:18s} not correctly rounded on {per[fn]} of {total[fn]} rows")

    for msg in failures[:40]:
        print("FAILED:", msg)
    if len(failures) > 40:
        print(f"... and {len(failures) - 40} more")
    print("validate: " + ("ok" if not failures else f"{len(failures)} failures"))
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))

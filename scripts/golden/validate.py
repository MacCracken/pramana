def km_exp_tables(root):
    """Reads kimiya's exp core data from the vendored src/crmath_data.cyr: the 2^(j/512) table's A_j and B_j words and
    the reduction and Taylor constants, as the port loads them."""
    text = (root / "src" / "crmath_data.cyr").read_text(encoding="utf-8")
    block = text[text.index("var _PMN_KM_CR_EXP_T: i64[2048] = {"):]
    block = block[block.index("{") + 1:block.index("}")]
    words = [from_bits(int(w, 16)) for w in re.findall(r"0x[0-9A-Fa-f]{16}", block)]
    if len(words) != 2048:
        raise SystemExit("kimiya's exp table: expected 2,048 words")
    KM_EXP["T"] = words
    for name in ("INVLN2N", "L1", "L2", "P3", "P4", "P5"):
        m = re.search(rf"var _PMN_KM_CR_EXP_{name} = (0x[0-9A-Fa-f]{{16}});", text)
        KM_EXP[name] = from_bits(int(m.group(1), 16))
    if bits(KM_EXP["INVLN2N"]) != bits(INVLN2N):
        raise SystemExit("kimiya's INVLN2N differs from 512/ln 2 rounded")


def t_dd_add(ah, al, bh, bl):
    s, e = t_two_sum(ah, bh)
    return t_fast_two_sum(s, e + (al + bl))


def t_dd_mul_d(ah, al, b):
    p, e = t_two_prod(ah, b)
    return t_fast_two_sum(p, e + al * b)


def t_dd_div(ah, al, bh, bl):
    q1 = ah / bh
    p, pe = t_two_prod(q1, bh)
    r3 = (((ah - p) - pe) + al) - q1 * bl
    return t_fast_two_sum(q1, r3 / bh)


def t_exp_core(xh, xl):
    """kimiya's exp core, `_pmn_km_exp_core` in src/crmath.cyr, operation for operation: (hi, lo, E) with hi + lo within
    about 2^-70 of e^(xh + xl)/2^E, lo unnormalized when r1 = 0."""
    if not KM_EXP:
        km_exp_tables(Path(__file__).resolve().parents[2])
    T = KM_EXP["T"]
    tt = (xh * KM_EXP["INVLN2N"]) + 6755399441055744.0
    kd = tt - 6755399441055744.0
    k = bits(tt) - 0x4338000000000000
    j = k & 511
    e = k >> 9
    rh = xh - (kd * KM_EXP["L1"])
    s = (kd * KM_EXP["L2"]) - xl
    r = rh - s
    rl = (rh - r) - s
    c = r + 49152.0
    r1 = c - 49152.0
    r2 = r - r1
    z = r * r
    q = (z * (0.5 + (r * KM_EXP["P3"]))) + ((z * z) * (KM_EXP["P4"] + (r * KM_EXP["P5"])))
    a, b = T[4 * j], T[4 * j + 1]
    p1 = a * r1
    hi = a + p1
    e1 = p1 - (hi - a)
    rlq = rl + q
    lo = (e1 + b) + ((a * (r2 + rlq)) + (b * (r + rlq)))
    return hi, lo, e


def t_dd_expm1(th, tl):
    if abs(th) < 0.125:
        sh, sl, ph, pl = th, tl, th, tl
        k = 2
        while k < 40:
            mh, ml = t_dd_mul(ph, pl, th, tl)
            ph, pl = t_dd_div(mh, ml, float(k), 0.0)
            sh, sl = t_dd_add(sh, sl, ph, pl)
            if abs(ph) < abs(sh) * 2.0 ** -62:
                break
            k += 1
        return sh, sl
    if th < -700.0:
        return -1.0, 0.0
    eh, el, e = t_exp_core(th, tl)
    s = math.ldexp(1.0, e)
    return t_dd_add(eh * s, el * s, -1.0, 0.0)


def t_scale(r, e):
    """_pmn_dd_scale: 2^e·r in two exact steps (e/2 truncated, as the port's integer division)."""
    e1 = -((-e) // 2) if e < 0 else e // 2
    return (r * math.ldexp(1.0, e1)) * math.ldexp(1.0, e - e1)


def t_lngamma1p_dd(f):
    if f == 0.0:
        return 0.0, 0.0
    if not ZETA:
        ZETA.extend(mpfr_ref.zeta_table())
    (gh, gl), zt, zm = ZETA
    y, table = f, zt
    if f > 0.5:
        y, table = f - 1.0, zm
        oh, ol = t_two_sum(1.0, -gh)
        ch, cl = oh, ol - gl
    else:
        ch, cl = -gh, -gl
    acc, accl = t_dd_mul_d(ch, cl, y)
    ph, pl = y, 0.0
    for k in range(2, 65):
        ph, pl = t_dd_mul_d(ph, pl, y)
        th, tl = t_dd_mul(table[k][0], table[k][1], ph, pl)
        uh, ul = t_dd_div(th, tl, float(k), 0.0)
        if k & 1:
            uh, ul = -uh, -ul
        acc, accl = t_dd_add(acc, accl, uh, ul)
        if abs(uh) < abs(acc) * 2.0 ** -62:
            break
    return acc, accl


def t_lngamma_small_dd(a):
    if a < 1.0:
        gh, gl = t_lngamma1p_dd(a)
        lh, ll = mpfr_ref.ln_dd(a)
        return t_dd_add(gh, gl, -lh, -ll)
    mf = math.floor(a)
    f, m = a - mf, int(mf)
    g2h, g2l = t_lngamma1p_dd(f)
    if m < 2:
        return g2h, g2l
    zh, zl = t_two_sum(1.0, f)
    for j in range(2, m):
        th, tl = t_two_sum(float(j), f)
        zh, zl = t_dd_mul(zh, zl, th, tl)
    lzh, lzl = mpfr_ref.ln_dd(zh)
    return t_dd_add(g2h, g2l, lzh, lzl + zl / zh)


def t_lnpre(a, x):
    """The prefactor's exponent a ln x − x − lnΓ(a) as a double-double."""
    if a < 10.0:
        lh, ll = mpfr_ref.ln_dd(x)
        th, tl = t_dd_mul_d(lh, ll, a)
        sh, sl = t_dd_add(th, tl, -x, 0.0)
        gh, gl = t_lngamma_small_dd(a)
        return t_dd_add(sh, sl, -gh, -gl)
    dh, dl = t_two_sum(x, -a)
    uh, ul = t_dd_div(dh, dl, a, 0.0)
    fh = fl = 0.0
    lah, lal = mpfr_ref.ln_dd(a)
    if abs(uh) <= 0.25:
        wh, wl = -uh, -ul
        ph, pl = t_dd_mul(wh, wl, wh, wl)
        for k in range(2, 200):
            th2, tl2 = t_dd_div(ph, pl, float(k), 0.0)
            fh, fl = t_dd_add(fh, fl, th2, tl2)
            if abs(th2) < abs(fh) * 2.0 ** -62:
                break
            ph, pl = t_dd_mul(ph, pl, wh, wl)
    else:
        lxh, lxl = mpfr_ref.ln_dd(x)
        l1h, l1l = t_dd_add(lxh, lxl, -lah, -lal)
        fh, fl = t_dd_add(uh, ul, -l1h, -l1l)
    ah, al = t_dd_mul_d(fh, fl, a)
    tph, tpm = 2.0 * math.pi, 2.0 * PI_L
    lph, lpl = mpfr_ref.ln_dd(tph)
    r1h, r1l = t_dd_add(0.5 * lah, 0.5 * lal, -ah, -al)
    r2h, r2l = t_dd_add(r1h, r1l, -(0.5 * lph), -(0.5 * (lpl + tpm / tph)))
    return t_dd_add(r2h, r2l, -sp_stirling(None, None, a), 0.0)


def t_gi_series(a, x):
    sh, sl, th, tl = 1.0, 0.0, 1.0, 0.0
    cap = 2000 + 100 * int(math.sqrt(a))
    for n in range(1, cap):
        dh, dl = t_two_sum(a, float(n))
        qh, ql = t_dd_div(x, 0.0, dh, dl)
        th, tl = t_dd_mul(th, tl, qh, ql)
        sh, sl = t_dd_add(sh, sl, th, tl)
        if th * x < (sh * 2.0 ** -62) * ((a - x) + (float(n) + 1.0)):
            break
    return sh, sl


def t_gi_cf(a, x):
    tiny = 2.0 ** -1022
    bh, bl0 = t_two_sum(x, -a)
    bh, bl = t_dd_add(bh, bl0, 1.0, 0.0)
    dh, dl = t_dd_div(1.0, 0.0, bh, bl)
    hh, hl = dh, dl
    ch = cl = 0.0
    cap = 2000 + 100 * int(math.sqrt(a))
    for i in range(1, cap):
        fi = float(i)
        ih, il = t_two_sum(fi, -a)
        anh, anl = t_dd_mul_d(ih, il, fi)
        anh, anl = -anh, -anl
        bh, bl = t_dd_add(bh, bl, 2.0, 0.0)
        adh, adl = t_dd_mul(anh, anl, dh, dl)
        d2h, d2l = t_dd_add(adh, adl, bh, bl)
        if abs(d2h) < tiny:
            d2h, d2l = tiny, 0.0
        if i == 1:
            ch, cl = bh, bl
        else:
            qh, ql = t_dd_div(anh, anl, ch, cl)
            ch, cl = t_dd_add(bh, bl, qh, ql)
        if abs(ch) < tiny:
            ch, cl = tiny, 0.0
        dh, dl = t_dd_div(1.0, 0.0, d2h, d2l)
        delh, dell = t_dd_mul(dh, dl, ch, cl)
        hh, hl = t_dd_mul(hh, hl, delh, dell)
        if abs(t_dd_add(delh, dell, -1.0, 0.0)[0]) < 2.0 ** -62:
            break
    return hh, hl


def t_gi_small_q(a, x):
    lgh, lgl = t_lngamma1p_dd(a)
    g1h, g1l = t_dd_expm1(lgh, lgl)
    lxh, lxl = mpfr_ref.ln_dd(x)
    alh, all_ = t_dd_mul_d(lxh, lxl, a)
    p1h, p1l = t_dd_expm1(alh, all_)
    th = tl = 0.0
    ch, cl = 1.0, 0.0
    for n in range(1, 80):
        fnn = float(n)
        mh, ml = t_dd_mul_d(ch, cl, -x)
        ch, cl = t_dd_div(mh, ml, fnn, 0.0)
        dh, dl = t_two_sum(a, fnn)
        uh, ul = t_dd_div(ch, cl, dh, dl)
        th, tl = t_dd_add(th, tl, uh, ul)
        if abs(uh) < abs(th) * 2.0 ** -62:
            break
    xah, xal = t_dd_add(1.0, 0.0, p1h, p1l)
    axh, axl = t_dd_mul_d(xah, xal, a)
    wh, wl = t_dd_mul(axh, axl, th, tl)
    dfh, dfl = t_dd_add(g1h, g1l, -p1h, -p1l)
    nmh, nml = t_dd_add(dfh, dfl, -wh, -wl)
    gmh, gml = t_dd_add(1.0, 0.0, g1h, g1l)
    qh, ql = t_dd_div(nmh, nml, gmh, gml)
    return qh + ql


def t1_gamma_core(a, x):
    """src/gammainc.cyr's (P, Q) for finite 0 < a ≤ 1e9 and finite x > 0, as the port computes them."""
    if x > 2.0 ** 990:
        return 1.0, 0.0
    mh, ml = t_lnpre(a, x)
    if mh < -1100.0:
        eh, el, e = 0.0, 0.0, -100000
    else:
        eh, el, e = t_exp_core(mh, ml)
    if x < a or (a < 1.0 and x < 1.1):
        sh, sl = t_gi_series(a, x)
        ad, es = (a * 2.0 ** 600, e + 600) if a < 2.0 ** -512 else (a, e)
        s2h, s2l = t_dd_div(sh, sl, ad, 0.0)
        ph, pl = t_dd_mul(eh, el, s2h, s2l)
        p = t_scale(ph + pl, es)
        if a < 1.0 and x < 1.1:
            return p, t_gi_small_q(a, x)
        s = 0.0 if e < -1000 else math.ldexp(1.0, e)
        qh, ql = t_dd_add(1.0, 0.0, -(ph * s), -(pl * s))
        return p, qh + ql
    hh, hl = t_gi_cf(a, x)
    qqh, qql = t_dd_mul(eh, el, hh, hl)
    q2 = t_scale(qqh + qql, e)
    s2 = 0.0 if e < -1000 else math.ldexp(1.0, e)
    p2h, p2l = t_dd_add(1.0, 0.0, -(qqh * s2), -(qql * s2))
    return p2h + p2l, q2


def t1_gamma_inc(K, L, a, x):
    """The port's gamma_inc: Rust's edges, and its Wilson–Hilferty form past a = 1e9 (sp_gamma_inc, on L's Φ); T1
    (t1_gamma_core) between."""
    if not (0.0 < a <= K["WH"] and 0.0 < x < math.inf):
        return sp_gamma_inc(K, L, a, x)
    return t1_gamma_core(a, x)


# The true (P, Q) of every golden gamma_inc row in T1's range (mpfr_ref.gamma_pq), keyed by the inputs' bits.
GAMMA_REF = {}


def ref_gamma_inc(K, L, a, x):
    """gamma_inc's own rows in the reference model: the true P and Q where T1 computes them, Rust's edges and its
    Wilson–Hilferty form elsewhere."""
    if not (0.0 < a <= K["WH"] and 0.0 < x < math.inf):
        return sp_gamma_inc(K, L, a, x)
    return GAMMA_REF[(bits(a), bits(x))]


def _gamma_ref_one(key):
    p, q = mpfr_ref.gamma_pq(from_bits(key[0]), from_bits(key[1]))
    return key, (bits(p), bits(q))


def gamma_reference(root, rows, wh):
    """Fills GAMMA_REF. mpfr_ref.gamma_pq takes up to about 10 s a pair at a = 1e9 through ctypes, so the pairs run in
    a process pool, largest shape first, and the results are cached in build/golden/ under a hash of gamma_pq's source
    and the MPFR version (a cache from another reference is never read)."""
    import hashlib
    import inspect
    import multiprocessing
    import os
    keys = set()
    for fn, cls, ins, outs, raw in rows:
        if fn == "math::gamma_inc" and len(ins) == 2 and 0.0 < ins[0] <= wh and 0.0 < ins[1] < math.inf:
            keys.add((bits(ins[0]), bits(ins[1])))
    tag = hashlib.sha256((inspect.getsource(mpfr_ref.gamma_pq) + mpfr_ref.VERSION).encode()).hexdigest()[:16]
    cache = root / "build" / "golden" / f"gamma_ref.{tag}.tsv"
    known = {}
    if cache.exists():
        for line in cache.read_text(encoding="utf-8").splitlines():
            ab, xb, pb, qb = (int(t, 16) for t in line.split())
            known[(ab, xb)] = (pb, qb)
    todo = sorted(keys - known.keys(), key=lambda k: -from_bits(k[0]))
    if todo:
        print(f"  gamma_inc reference: {len(todo)} pairs at 320 bits or more (cached in build/golden/)", flush=True)
        cache.parent.mkdir(parents=True, exist_ok=True)
        # Each pair is appended as it lands, so an interrupted run keeps what it computed.
        with multiprocessing.get_context("fork").Pool(os.cpu_count()) as pool, \
                open(cache, "a", encoding="utf-8") as out:
            for (a, x), (p, q) in pool.imap_unordered(_gamma_ref_one, todo):
                known[(a, x)] = (p, q)
                out.write(f"{a:016x} {x:016x} {p:016x} {q:016x}\n")
                out.flush()
    GAMMA_REF.clear()
    GAMMA_REF.update({k: (from_bits(v[0]), from_bits(v[1])) for k, v in known.items() if k in keys})


# ── the T1 incomplete beta (M2 part b5), as src/betainc.cyr computes it ──
# Every double-double step is the port's, in its order, on the helpers above; kimiya's ln and exp cores are MPFR's
# double-doubles of the same values, kimiya's correctly rounded ln is MPFR's, and γ and ζ(k) − 1 are MPFR's.
BETA_T1_MAX = 1e9   # src/special.cyr's beta_inc: T1 up to max(a, b) = 1e9, Rust's form (T0) past it


def t_ln_of_dd(h, l):
    lh, ll = mpfr_ref.ln_dd(h)
    return lh, ll + l / h


def t_bi_digamma(z):
    s, w = 0.0, z
    while w < 6.0:
        s = s - 1.0 / w
        w = w + 1.0
    lw = mpfr_ref.cr("log", w)
    iw = 1.0 / w
    i2 = iw * iw
    t = i2 * (0.083333333333333333 - i2 * (0.0083333333333333333 - i2 * 0.003968253968253968))
    return ((lw - 0.5 * iw) - t) + s


def t_bi_stirling_dd(zh, zl):
    rh, rl = t_dd_div(1.0, 0.0, zh, zl)
    r2h, r2l = t_dd_mul(rh, rl, rh, rl)
    cs = [t_dd_div(n, 0.0, d, 0.0) for n, d in ((1.0, 12.0), (1.0, 360.0), (1.0, 1260.0), (1.0, 1680.0),
                                                 (1.0, 1188.0), (691.0, 360360.0), (1.0, 156.0))]
    th, tl = t_dd_mul(r2h, r2l, cs[6][0], cs[6][1])
    for k in (5, 4, 3, 2, 1, 0):
        uh, ul = t_dd_add(cs[k][0], cs[k][1], -th, -tl)
        if k == 0:
            return t_dd_mul(rh, rl, uh, ul)
        th, tl = t_dd_mul(r2h, r2l, uh, ul)


def t_bi_ln_sqrt_2pi():
    tph, tpm = 2.0 * math.pi, 2.0 * PI_L
    lph, lpl = mpfr_ref.ln_dd(tph)
    return 0.5 * lph, 0.5 * (lpl + tpm / tph)


def t_bi_lgamma_dd(zh, zl):
    if zh < 20.0:
        gh, gl = t_lngamma_small_dd(zh)
        if zl != 0.0:
            return t_dd_add(gh, gl, zl * t_bi_digamma(zh), 0.0)
        return gh, gl
    lh, ll0 = mpfr_ref.ln_dd(zh)
    ll = ll0 + zl / zh
    mh, ml = t_dd_add(zh, zl, -0.5, 0.0)
    ph, pl = t_dd_mul(mh, ml, lh, ll)
    qh, ql = t_dd_add(ph, pl, -zh, -zl)
    sph, spl = t_bi_ln_sqrt_2pi()
    r1h, r1l = t_dd_add(qh, ql, sph, spl)
    sth, stl = t_bi_stirling_dd(zh, zl)
    return t_dd_add(r1h, r1l, sth, stl)


def t_bi_quot(a, w):
    if a < 2.0 ** -512:
        qh, ql = t_dd_div(a * 2.0 ** 600, 0.0, w, 0.0)
        return qh * 2.0 ** -600, ql * 2.0 ** -600
    return t_dd_div(a, 0.0, w, 0.0)


def t_bi_log1p_g(th, tl):
    sh, sl, ph, pl = 1.0, 0.0, 1.0, 0.0
    for k in range(2, 80):
        nh, nl = t_dd_mul(ph, pl, th, tl)
        ph, pl = -nh, -nl
        qh, ql = t_dd_div(ph, pl, float(k), 0.0)
        sh, sl = t_dd_add(sh, sl, qh, ql)
        if abs(qh) < sh * 2.0 ** -62 or qh == 0.0:
            break
    return sh, sl


def t_bi_ln1p_ratio(a, w):
    if 4.0 * a <= w:
        th, tl = t_bi_quot(a, w)
        gh, gl = t_bi_log1p_g(th, tl)
        return t_dd_mul(th, tl, gh, gl)
    swh, swl = t_two_sum(w, a)
    l1h, l1l = t_ln_of_dd(swh, swl)
    l2h, l2l = mpfr_ref.ln_dd(w)
    return t_dd_add(l1h, l1l, -l2h, -l2l)


def t_bi_lgdiff_big(a, b):
    rh, rl = t_dd_div(1.0, 0.0, b, 0.0)
    sh, sl = t_two_sum(b, a)
    qh, ql = t_dd_div(1.0, 0.0, sh, sl)
    acch, accl = t_dd_div(1.0, 0.0, 12.0, 0.0)
    ph, pl, wh, wl = 1.0, 0.0, rh, rl
    coef = {3: (1.0, 360.0), 5: (1.0, 1260.0), 7: (1.0, 1680.0), 9: (1.0, 1188.0), 11: (691.0, 360360.0),
            13: (1.0, 156.0)}
    n = 1
    while n < 13:
        mh, ml = t_dd_mul(qh, ql, ph, pl)
        ph, pl = t_dd_add(wh, wl, mh, ml)
        n += 1
        wh, wl = t_dd_mul(wh, wl, rh, rl)
        if n & 1:
            ch, cl = t_dd_div(coef[n][0], 0.0, coef[n][1], 0.0)
            th, tl = t_dd_mul(ch, cl, ph, pl)
            if (n & 3) == 3:
                th, tl = -th, -tl
            acch, accl = t_dd_add(acch, accl, th, tl)
    rqh, rql = t_dd_mul(rh, rl, qh, ql)
    aqh, aql = t_dd_mul_d(rqh, rql, a)
    dsh, dsl = t_dd_mul(aqh, aql, acch, accl)
    if 4.0 * a <= b:
        tth, ttl = t_bi_quot(a, b)
        gh, gl = t_bi_log1p_g(tth, ttl)
        hrh, hrl = t_dd_mul_d(rh, rl, -0.5)
        fh, fl = t_dd_add(1.0, 0.0, hrh, hrl)
        fgh, fgl = t_dd_mul(fh, fl, gh, gl)
        t1h, t1l = t_dd_mul_d(fgh, fgl, a)
    else:
        lh, ll = t_bi_ln1p_ratio(a, b)
        bmh, bml = t_two_sum(b, -0.5)
        t1h, t1l = t_dd_mul(bmh, bml, lh, ll)
    lsh, lsl = t_ln_of_dd(sh, sl)
    l1h, l1l = t_dd_add(lsh, lsl, -1.0, 0.0)
    t2h, t2l = t_dd_mul_d(l1h, l1l, a)
    u1h, u1l = t_dd_add(t1h, t1l, t2h, t2l)
    return t_dd_add(u1h, u1l, -dsh, -dsl)


def t_bi_lgdiff_small(a, b):
    mf = math.floor(b) - 1.0
    m = int(mf)
    y1h, y1l = t_two_sum(b, -(mf + 2.0))
    y2h, y2l = t_dd_add(y1h, y1l, a, 0.0)
    if not ZETA:
        ZETA.extend(mpfr_ref.zeta_table())
    (gh, gl), zt, zm = ZETA
    oh, ol = t_two_sum(1.0, -gh)
    acch, accl = t_dd_mul_d(oh, ol - gl, a)
    dh, dl, ph, pl = a, 0.0, 1.0, 0.0
    for k in range(2, 65):
        ph, pl = t_dd_mul(ph, pl, y1h, y1l)
        t1h, t1l = t_dd_mul(y2h, y2l, dh, dl)
        t2h, t2l = t_dd_mul_d(ph, pl, a)
        dh, dl = t_dd_add(t1h, t1l, t2h, t2l)
        th, tl = t_dd_mul(zm[k][0], zm[k][1], dh, dl)
        uh, ul = t_dd_div(th, tl, float(k), 0.0)
        if k & 1:
            uh, ul = -uh, -ul
        acch, accl = t_dd_add(acch, accl, uh, ul)
    if m < 0:
        lh, ll = t_bi_ln1p_ratio(a, b)
        return t_dd_add(acch, accl, -lh, -ll)
    for i in range(1, m + 1):
        lh, ll = t_bi_ln1p_ratio(a, b - float(i))
        acch, accl = t_dd_add(acch, accl, lh, ll)
    return acch, accl


def t_bi_ln_ab(a, b):
    if a >= 1.0 and b < 20.0:
        g1h, g1l = t_bi_lgamma_dd(a, 0.0)
        lah, lal = mpfr_ref.ln_dd(a)
        h1h, h1l = t_dd_add(g1h, g1l, lah, lal)
        gbh, gbl = t_bi_lgamma_dd(b, 0.0)
        sh, sl = t_two_sum(a, b)
        gsh, gsl = t_bi_lgamma_dd(sh, sl)
        l1h, l1l = t_dd_add(h1h, h1l, gbh, gbl)
        return t_dd_add(l1h, l1l, -gsh, -gsl)
    if a < 1.0:
        ah, al = t_lngamma1p_dd(a)
    else:
        g3h, g3l = t_bi_lgamma_dd(a, 0.0)
        la2h, la2l = mpfr_ref.ln_dd(a)
        ah, al = t_dd_add(g3h, g3l, la2h, la2l)
    dh, dl = t_bi_lgdiff_big(a, b) if b >= 20.0 else t_bi_lgdiff_small(a, b)
    return t_dd_add(ah, al, -dh, -dl)


def t_bi_phi(uh, ul, lh, ll):
    if abs(uh) <= 0.25:
        fh = fl = 0.0
        wh, wl = -uh, -ul
        ph, pl = t_dd_mul(wh, wl, wh, wl)
        for k in range(2, 200):
            th, tl = t_dd_div(ph, pl, float(k), 0.0)
            fh, fl = t_dd_add(fh, fl, th, tl)
            if abs(th) < abs(fh) * 2.0 ** -62 or th == 0.0:
                break
            ph, pl = t_dd_mul(ph, pl, wh, wl)
        return fh, fl
    return t_dd_add(uh, ul, -lh, -ll)


def t_bi_lnpre_large(a, b, xh, xl, yh, yl):
    sh, sl = t_two_sum(a, b)
    bxh, bxl = t_dd_mul_d(xh, xl, b)
    ayh, ayl = t_dd_mul_d(yh, yl, a)
    lmh, lml = t_dd_add(bxh, bxl, -ayh, -ayl)
    uah, ual = t_dd_div(lmh, lml, a, 0.0)
    ubh, ubl = t_dd_div(-lmh, -lml, b, 0.0)
    lah, lal = mpfr_ref.ln_dd(a)
    lbh, lbl = mpfr_ref.ln_dd(b)
    lsh, lsl = t_ln_of_dd(sh, sl)
    l1h = l1l = l2h = l2l = 0.0
    if abs(uah) > 0.25:
        lxh, lxl = t_ln_of_dd(xh, xl)
        v1h, v1l = t_dd_add(lsh, lsl, lxh, lxl)
        l1h, l1l = t_dd_add(v1h, v1l, -lah, -lal)
    if abs(ubh) > 0.25:
        lyh, lyl = t_ln_of_dd(yh, yl)
        w1h, w1l = t_dd_add(lsh, lsl, lyh, lyl)
        l2h, l2l = t_dd_add(w1h, w1l, -lbh, -lbl)
    pah, pal = t_bi_phi(uah, ual, l1h, l1l)
    pbh, pbl = t_bi_phi(ubh, ubl, l2h, l2l)
    fah, fal = t_dd_mul_d(pah, pal, a)
    fbh, fbl = t_dd_mul_d(pbh, pbl, b)
    h1h, h1l = t_dd_add(lbh, lbl, -lah, -lal)
    h2h, h2l = t_dd_add(h1h, h1l, -lsh, -lsl)
    sah, sal = t_bi_stirling_dd(a, 0.0)
    sbh, sbl = t_bi_stirling_dd(b, 0.0)
    ssh, ssl = t_bi_stirling_dd(sh, sl)
    c1h, c1l = t_dd_add(sah, sal, sbh, sbl)
    c2h, c2l = t_dd_add(c1h, c1l, -ssh, -ssl)
    qh, ql = t_bi_ln_sqrt_2pi()
    m1h, m1l = t_dd_add(0.5 * h2h, 0.5 * h2l, -fah, -fal)
    m2h, m2l = t_dd_add(m1h, m1l, -fbh, -fbl)
    m3h, m3l = t_dd_add(m2h, m2l, -qh, -ql)
    return t_dd_add(m3h, m3l, -c2h, -c2l)



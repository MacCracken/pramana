# ── rng: 1.3.0's SimpleRng, xorshift64 (13, 7, 17), modelled in Python ──


def xorshift_draws(seed, n):
    """The bits of SimpleRng::new(seed)'s first n draws: each step, then (x >> 11) / 2^53."""
    x = seed or 1
    for _ in range(n):
        x ^= (x << 13) & MASK64
        x ^= x >> 7
        x ^= (x << 17) & MASK64
        yield bits((x >> 11) / 9007199254740992.0)


# ── linalg: hisab 1.4.0's Cholesky factorization and solve (M3 part d1), term for term ──
def lin_cholesky(n, a):
    """hisab's cholesky on a flat row-major n×n list: the flat L, or None for its InvalidInput."""
    if n == 0:
        return None
    l = [0.0] * (n * n)
    for i in range(n):
        for j in range(i + 1):
            s = a[i * n + j]
            for k in range(j):
                s -= l[i * n + k] * l[j * n + k]
            if i == j:
                if s <= 0.0:
                    return None
                l[i * n + j] = math.sqrt(s)
            else:
                l[i * n + j] = fdiv(s, l[j * n + j])
    return l


def lin_cholesky_solve(n, l, b):
    """hisab's cholesky_solve: forward then back substitution, reading L's lower triangle."""
    y = [0.0] * n
    for i in range(n):
        s = b[i]
        for j in range(i):
            s -= l[i * n + j] * y[j]
        y[i] = fdiv(s, l[i * n + i])
    x = [0.0] * n
    for i in range(n - 1, -1, -1):
        s = y[i]
        for j in range(i + 1, n):
            s -= l[j * n + i] * x[j]
        x[i] = fdiv(s, l[i * n + i])
    return x


def check_linalg(rows):
    """Every linalg row re-derived by the transcription above (class A: arithmetic and the correctly rounded √)."""
    failures, by_fn = [], {}

    def same_all(a, b):
        return len(a) == len(b) and all(same(x, y) if isinstance(y, float) else x == y for x, y in zip(a, b))

    for fn, cls, ins, outs, raw in rows:
        n = ins[0]
        k = 1
        if not (isinstance(ins[k], str) and ins[k] == f"v:{n * n}"):
            failures.append(f"linalg: {fn}: a malformed matrix")
            continue
        a = ins[k + 1:k + 1 + n * n]
        if fn == "linalg::cholesky":
            l = lin_cholesky(n, a)
            want = ["E:InvalidParameter"] if l is None else [f"v:{n * n}"] + l
        elif fn == "linalg::cholesky_solve":
            b = ins[k + 2 + n * n:]
            if ins[k + 1 + n * n] != f"v:{n}" or len(b) != n:
                failures.append(f"linalg: {fn}: a malformed right side")
                continue
            want = [f"v:{n}"] + lin_cholesky_solve(n, a, b)
        else:
            failures.append(f"linalg: no model for {fn}")
            continue
        ok = same_all(outs, want)
        stat = by_fn.setdefault(fn, [0, 0])
        stat[0 if ok else 1] += 1
        if not ok:
            failures.append(f"linalg: {fn} at n = {n}: recorded {outs[:4]!r}, modelled {want[:4]!r}")
    return failures, by_fn


def check_rng(rows):
    failures, by_fn = [], {}
    for fn, _cls, ins, outs, _raw in rows:
        seed, n = ins[0] % (1 << 64), ins[1]
        if fn == "SimpleRng::next_f64":
            want = [f"v:{n}"] + [from_bits(b) for b in xorshift_draws(seed, n)]
        elif fn == "SimpleRng::digest":
            h = 0xCBF29CE484222325
            for b in xorshift_draws(seed, n):
                h = ((h ^ b) * 0x100000001B3) & MASK64
            want = [h - (1 << 64) if h >= 1 << 63 else h]
        else:
            failures.append(f"rng: no rule for {fn}")
            continue
        ok = len(outs) == len(want) and all(same(g, w) if isinstance(w, float) else g == w for g, w in zip(outs, want))
        stat = by_fn.setdefault(fn, [0, 0])
        stat[0 if ok else 1] += 1
        if not ok:
            failures.append(f"rng: {fn}({seed}, {n}) differs from the model")
    return failures, by_fn


# ── combinatorics: Python's exact integers in 1.3.0's checked u128 loops ──

U128_MAX = (1 << 128) - 1


def counting(fn, n, r):
    """factorial / permutations / combinations as 1.3.0 computes them: ("ok", value) or ("err", variant)."""
    if fn == "combinatorics::factorial":
        if n > 34:
            return ("err", "ComputationError")
        acc = 1
        for k in range(2, n + 1):
            acc *= k
            if acc > U128_MAX:
                return ("err", "ComputationError")
        return ("ok", acc)
    if r > n:
        return ("err", "InvalidParameter")
    acc = 1
    if fn == "combinatorics::permutations":
        for k in range(r):
            acc *= n - k
            if acc > U128_MAX:                       # each product checked: the loop stops at the first overflow
                return ("err", "ComputationError")
        return ("ok", acc)
    k = min(r, n - r)
    for j in range(k):
        acc *= n - j
        if acc > U128_MAX:                           # the product before the division: an intermediate can overflow
            return ("err", "ComputationError")
        acc //= j + 1
    return ("ok", acc)


def stirling(n, pow_fn):
    """stirling_approx(n) in Rust's operation order, with the pow given: √((2π)·n) · (n / e)^n."""
    if n == 0:
        return 1.0
    nf = float(n)                                    # Rust's `n as f64`: to nearest, ties to even
    return math.sqrt((2.0 * math.pi) * nf) * pow_fn(nf / math.e, nf)



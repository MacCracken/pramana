_libm = ctypes.CDLL("libm.so.6")
GLIBC = {
    "f64::exp": "exp",
    "f64::ln": "log",
    "f64::ln_1p": "log1p",
    "f64::exp_m1": "expm1",
    "f64::sin": "sin",
    "f64::cos": "cos",
    "f64::tan": "tan",
    "f64::atan": "atan",
    "f64::log2": "log2",
}
for _name in list(GLIBC.values()) + ["pow"]:
    _fn = getattr(_libm, _name)
    _fn.restype = ctypes.c_double
    _fn.argtypes = [ctypes.c_double, ctypes.c_double] if _name == "pow" else [ctypes.c_double]
MPFR_NAME = dict(GLIBC, **{"f64::cbrt": "cbrt"})


def correctly_rounded(fn, ins):
    if fn == "f64::powf":
        return mpfr_ref.cr2("pow", ins[0], ins[1])
    return mpfr_ref.cr(MPFR_NAME[fn], ins[0])


def expected_math(fn, ins, outs):
    """What the row's output must be, recomputed without the oracle; None for a function this file doesn't know."""
    x = ins[0] if ins else None
    if fn == "f64::sqrt":
        return r_sqrt(x)
    if fn == "f64::abs":
        return math.fabs(x)
    if fn == "f64::floor":
        return r_floor(x)
    if fn == "f64::fract":
        return r_fract(x)
    if fn in ("f64::max", "f64::min"):
        return r_maxmin(fn, ins[0], ins[1], outs[0])
    if fn == "f64::clamp":
        return r_clamp(*ins)
    if fn == "f64::is_finite":
        return int(math.isfinite(x))
    if fn == "f64::is_nan":
        return int(math.isnan(x))
    if fn == "f64::total_cmp":
        a, b = total_key(ins[0]), total_key(ins[1])
        return (a > b) - (a < b)
    if fn == "f64::as_usize":
        return to_i64(r_as_usize(x))
    if fn == "u64::as_f64":
        return float(x & MASK64)
    if fn == "f64::high_word":
        return bits(x) >> 32
    if fn == "f64::low_masked":
        return from_bits(bits(x) & 0xFFFF_FFFF_0000_0000)
    if fn.startswith("f64::powi"):
        return powi(x, int(fn[len("f64::powi"):]))
    if fn == "f64::powf":
        return _libm.pow(ins[0], ins[1])
    if fn in GLIBC:
        return getattr(_libm, GLIBC[fn])(x)
    if fn == "f64::cbrt":
        return mpfr_ref.cr("cbrt", x)
    return None


# ── fmt: serde_json's f64 text, from Python's shortest digits ──


def json_f64_text(x: float) -> str:
    """serde_json 1.0.154's text for x: positional for decimal exponents −5 … 15 (".0" on an integer), otherwise
    d.ddde±x; `null` for NaN and ±∞. The digits are Python's repr's, normalised to 0.D × 10^k."""
    if math.isnan(x) or math.isinf(x):
        return "null"
    sign = "-" if math.copysign(1.0, x) < 0 else ""
    if x == 0.0:
        return sign + "0.0"
    d = Decimal(repr(abs(x))).normalize()
    _, digit_tuple, exp = d.as_tuple()
    digits = "".join(str(t) for t in digit_tuple)
    n = len(digits)
    k = n + exp
    ex = k - 1
    if -5 <= ex <= 15:
        if k <= 0:
            body = "0." + "0" * (-k) + digits
        elif k >= n:
            body = digits + "0" * (k - n) + ".0"
        else:
            body = digits[:k] + "." + digits[k:]
    else:
        body = digits[0] + ("." + digits[1:] if n > 1 else "") + "e" + ("+" if ex >= 0 else "-") + str(abs(ex))
    return sign + body


def check_fmt(rows):
    failures, ok = [], 0
    for fn, _cls, ins, outs, _raw in rows:
        if fn != "f64::to_json":
            failures.append(f"fmt: no rule for {fn}")
            continue
        got = urllib.parse.unquote(outs[0][len("s:"):])
        want = json_f64_text(ins[0])
        if got == want:
            ok += 1
        else:
            failures.append(f"fmt: {fn}({ins[0]!r}) recorded {got!r}, recomputed {want!r}")
    return failures, ok


# ── json: serde_json 1.0.154's reading, modelled from its source (de.rs, read.rs) ──


class SerdeRefusal(Exception):
    pass


JSON_WS = b" \t\n\r"
U64_MAX = (1 << 64) - 1


class SerdeModel:
    """serde_json's from_slice for one document: the strict RFC 8259 grammar, whitespace = space, tab, LF, CR, and
    serde's rules for each value type (`float_roundtrip`: every float correctly rounded)."""

    def __init__(self, doc: bytes):
        self.b, self.i = doc, 0

    def peek(self):
        return self.b[self.i] if self.i < len(self.b) else None

    def ws(self):
        while self.i < len(self.b) and self.b[self.i] in JSON_WS:
            self.i += 1

    def expect(self, lit: bytes):
        if self.b[self.i:self.i + len(lit)] != lit:
            raise SerdeRefusal("expected " + lit.decode())
        self.i += len(lit)

    def end(self):
        self.ws()
        if self.i != len(self.b):
            raise SerdeRefusal("trailing characters")

    def number(self):
        """('u', int), ('i', int) or ('f', float) as serde_json's ParserNumber, or a refusal."""
        text, neg, is_float = self.number_text()
        if not is_float:
            mag = int(text.lstrip("-"))
            if not neg and mag <= U64_MAX:
                return ("u", mag)
            if neg and mag == 0:
                return ("f", -0.0)                   # parse_integer: -0 is the float -0.0
            if neg and mag <= 1 << 63:
                return ("i", -mag)
            try:
                return ("f", float(-mag if neg else mag))
            except OverflowError:
                raise SerdeRefusal("number out of range")
        x = float(text)
        if math.isinf(x):
            raise SerdeRefusal("number out of range")
        return ("f", x)

    def number_text(self):
        """The strict number grammar alone (ignore_integer's too): (text, negative, has a fraction or exponent)."""
        st = self.i
        neg = self.peek() == 0x2D
        if neg:
            self.i += 1
        c = self.peek()
        if c == 0x30:
            self.i += 1
            if self.peek() is not None and 0x30 <= self.peek() <= 0x39:
                raise SerdeRefusal("leading zero")
        elif c is not None and 0x31 <= c <= 0x39:
            while self.peek() is not None and 0x30 <= self.peek() <= 0x39:
                self.i += 1
        else:
            raise SerdeRefusal("invalid number")
        is_float = False
        if self.peek() == 0x2E:
            is_float = True
            self.i += 1
            if not (self.peek() is not None and 0x30 <= self.peek() <= 0x39):
                raise SerdeRefusal("no digit after the point")
            while self.peek() is not None and 0x30 <= self.peek() <= 0x39:
                self.i += 1
        if self.peek() in (0x65, 0x45):
            is_float = True
            self.i += 1
            if self.peek() in (0x2B, 0x2D):
                self.i += 1
            if not (self.peek() is not None and 0x30 <= self.peek() <= 0x39):
                raise SerdeRefusal("no exponent digit")
            while self.peek() is not None and 0x30 <= self.peek() <= 0x39:
                self.i += 1
        return self.b[st:self.i].decode("ascii"), neg, is_float

    def string(self) -> bytes:
        """parse_str with validation: escapes decoded, surrogates paired, control bytes refused, UTF-8 checked."""
        if self.peek() != 0x22:
            raise SerdeRefusal("expected a string")
        self.i += 1
        out = bytearray()
        while True:
            c = self.peek()
            if c is None:
                raise SerdeRefusal("EOF in a string")
            self.i += 1
            if c == 0x22:
                break
            if c < 0x20:
                raise SerdeRefusal("control character in a string")
            if c != 0x5C:
                out.append(c)
                continue
            e = self.peek()
            if e is None:
                raise SerdeRefusal("EOF in an escape")
            self.i += 1
            simple = {0x22: 0x22, 0x5C: 0x5C, 0x2F: 0x2F, 0x62: 8, 0x66: 12, 0x6E: 10, 0x72: 13, 0x74: 9}
            if e in simple:
                out.append(simple[e])
                continue
            if e != 0x75:
                raise SerdeRefusal("invalid escape")
            cp = self.hex4()
            if 0xDC00 <= cp <= 0xDFFF:
                raise SerdeRefusal("lone trailing surrogate")
            if 0xD800 <= cp <= 0xDBFF:
                if self.b[self.i:self.i + 2] != b"\\u":
                    raise SerdeRefusal("lone leading surrogate")
                self.i += 2
                lo = self.hex4()
                if not 0xDC00 <= lo <= 0xDFFF:
                    raise SerdeRefusal("lone leading surrogate")
                cp = 0x10000 + ((cp - 0xD800) << 10) + (lo - 0xDC00)
            out += chr(cp).encode("utf-8")
        try:
            out.decode("utf-8")
        except UnicodeDecodeError:
            raise SerdeRefusal("invalid UTF-8")
        return bytes(out)

    def ignore_str(self):
        """ignore_str, after the opening quote: control bytes and malformed escapes refuse; nothing else is checked
        (no UTF-8, no surrogate pairing)."""
        while True:
            c = self.peek()
            if c is None:
                raise SerdeRefusal("EOF in a string")
            self.i += 1
            if c == 0x22:
                return
            if c < 0x20:
                raise SerdeRefusal("control character in a string")
            if c == 0x5C:
                e = self.peek()
                if e is None:
                    raise SerdeRefusal("EOF in an escape")
                self.i += 1
                if e == 0x75:
                    self.hex4()
                elif e not in b'"\\/bfnrt':
                    raise SerdeRefusal("invalid escape")

    def ignore_value(self):
        """ignore_value: any JSON value, checked for syntax only, nested without a depth limit."""
        self.ws()
        c = self.peek()
        if c == 0x6E:
            self.expect(b"null")
        elif c == 0x74:
            self.expect(b"true")
        elif c == 0x66:
            self.expect(b"false")
        elif c is not None and (c == 0x2D or 0x30 <= c <= 0x39):
            self.number_text()
        elif c == 0x22:
            self.i += 1
            self.ignore_str()
        elif c in (0x5B, 0x7B):
            close = 0x5D if c == 0x5B else 0x7D
            self.i += 1
            self.ws()
            if self.peek() == close:
                self.i += 1
                return
            while True:
                if c == 0x7B:
                    self.ws()
                    if self.peek() != 0x22:
                        raise SerdeRefusal("key must be a string")
                    self.i += 1
                    self.ignore_str()
                    self.ws()
                    if self.peek() != 0x3A:
                        raise SerdeRefusal("expected a colon")
                    self.i += 1
                self.ignore_value()
                self.ws()
                d = self.peek()
                if d == close:
                    self.i += 1
                    return
                if d != 0x2C:
                    raise SerdeRefusal("expected , or a close")
                self.i += 1
        else:
            raise SerdeRefusal("expected a value")

    def struct(self, fields):
        """serde derive's visit_map and visit_seq through deserialize_struct."""
        self.ws()
        c = self.peek()
        if c == 0x5B:
            self.i += 1
            parts = []
            for k, (_name, ty) in enumerate(fields):
                self.ws()
                c = self.peek()
                if c is None or c == 0x5D:
                    raise SerdeRefusal("invalid length")
                if k > 0:
                    if c != 0x2C:
                        raise SerdeRefusal("expected , or ]")
                    self.i += 1
                    self.ws()
                    if self.peek() == 0x5D:
                        raise SerdeRefusal("trailing comma")
                parts.append(self.value(ty))
            self.ws()
            if self.peek() != 0x5D:
                raise SerdeRefusal("trailing characters in the sequence")
            self.i += 1
            return [t for part in parts for t in part]
        if c != 0x7B:
            raise SerdeRefusal("invalid type")
        self.i += 1
        got, first = {}, True
        names = {name.encode(): (name, ty) for name, ty in fields}
        while True:
            self.ws()
            c = self.peek()
            if c is None:
                raise SerdeRefusal("EOF in an object")
            if c == 0x7D and first:
                self.i += 1
                break
            if not first:
                if c == 0x7D:
                    self.i += 1
                    break
                if c != 0x2C:
                    raise SerdeRefusal("expected , or }")
                self.i += 1
                self.ws()
                c = self.peek()
            if c != 0x22:
                raise SerdeRefusal("key must be a string (or a trailing comma)")
            first = False
            key = self.string()                      # a struct's keys are parsed, the unknown ones too
            self.ws()
            if self.peek() != 0x3A:
                raise SerdeRefusal("expected a colon")
            self.i += 1
            if key in names:
                if key in got:
                    raise SerdeRefusal("duplicate field")
                got[key] = self.value(names[key][1])
            else:
                self.ignore_value()
        for name, _ty in fields:
            if name.encode() not in got:
                raise SerdeRefusal("missing field")
        return [t for name, _ty in fields for t in got[name.encode()]]

    def enum(self, enum_name, variants, payload):
        """An externally tagged enum: unit variants (payload None) or newtype variants holding `payload`."""
        self.ws()
        c = self.peek()
        if c == 0x22:
            name = self.string()
            if payload is not None or name.decode("utf-8") not in variants:
                raise SerdeRefusal("unknown variant, or a unit variant for a newtype")
            return [f"e:{enum_name}.{name.decode()}"]
        if c != 0x7B:
            raise SerdeRefusal("expected an enum")
        self.i += 1
        self.ws()
        if self.peek() != 0x22:
            raise SerdeRefusal("expected the variant")
        name = self.string()
        if name.decode("utf-8") not in variants:
            raise SerdeRefusal("unknown variant")
        self.ws()
        if self.peek() != 0x3A:
            raise SerdeRefusal("expected a colon")
        self.i += 1
        if payload is None:
            self.ws()
            self.expect(b"null")
            toks = []
        else:
            toks = self.value(payload)
        self.ws()
        if self.peek() != 0x7D:
            raise SerdeRefusal("expected }")
        self.i += 1
        return [f"e:{enum_name}.{name.decode()}"] + toks

    def hex4(self) -> int:
        h = self.b[self.i:self.i + 4]
        if len(h) < 4 or any(chr(x) not in "0123456789abcdefABCDEF" for x in h):
            raise SerdeRefusal("invalid hex escape")
        self.i += 4
        return int(h, 16)

    def value(self, ty: str):
        """The tokens serde's Deserialize for `ty` reads at the cursor."""
        self.ws()
        c = self.peek()
        if ty in ("f64", "u64", "usize"):
            if c is None or not (c == 0x2D or 0x30 <= c <= 0x39):
                raise SerdeRefusal("invalid type")
            kind, v = self.number()
            if ty == "f64":
                return [float(v)]                    # u64 and i64 convert as Rust's `as f64`: correctly rounded
            if kind != "u":
                raise SerdeRefusal("invalid type or value")
            return [v - (1 << 64) if v >= 1 << 63 else v]
        if ty == "bool":
            if c == 0x74:
                self.expect(b"true")
                return [1]
            if c == 0x66:
                self.expect(b"false")
                return [0]
            raise SerdeRefusal("invalid type")
        if ty == "String":
            return ["s:" + pct_bytes(self.string())]
        if ty == "SimpleRng":
            state = self.struct([("state", "u64")])[0]   # SimpleRngRepr, then SimpleRng::new: 0 becomes 1
            return [1 if state == 0 else state]
        if ty in JSON_VALIDATED:
            fields, check = JSON_VALIDATED[ty]
            vals = self.struct(fields)                   # the Repr, then the constructor: its refusal is an error
            if not check(*vals):
                raise SerdeRefusal("invalid value (the constructor refuses it)")
            return vals
        if ty in JSON_STRUCTS:
            return self.struct(JSON_STRUCTS[ty])
        if ty in JSON_ENUMS:
            return self.enum(ty, *JSON_ENUMS[ty])
        if ty.startswith("Vec<") and ty.endswith(">"):
            inner = ty[4:-1]
            if c != 0x5B:
                raise SerdeRefusal("invalid type")
            self.i += 1
            elems = []
            self.ws()
            if self.peek() == 0x5D:
                self.i += 1
                return [f"v:0"]
            while True:
                elems.append(self.value(inner))
                self.ws()
                c = self.peek()
                if c == 0x2C:
                    self.i += 1
                    self.ws()
                    if self.peek() == 0x5D:
                        raise SerdeRefusal("trailing comma")
                    continue
                if c == 0x5D:
                    self.i += 1
                    break
                raise SerdeRefusal("expected , or ]")
            return [f"v:{len(elems)}"] + [t for e in elems for t in e]
        raise ValueError(f"no model for {ty}")



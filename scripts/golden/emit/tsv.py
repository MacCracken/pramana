"""Golden TSV, format 1 (scripts/golden/README.md): `fn <TAB> class <TAB> inputs <TAB> outputs <TAB> note`, the inputs and
outputs as space-separated typed tokens (`-` when empty). The note is a short human rendering for review; nothing
reads it."""
import struct
import urllib.parse

PROVENANCE = "pramana 1.3.0's models in Python (scripts/golden), libm: glibc 2.44 x86_64 fma"


def platform_provenance():
    """The libm platform this process runs on, in PROVENANCE's form: glibc's version and the machine."""
    import ctypes
    import platform
    libc = ctypes.CDLL("libc.so.6")
    libc.gnu_get_libc_version.restype = ctypes.c_char_p
    fma = ""
    try:
        flags = next(l for l in open("/proc/cpuinfo", encoding="utf-8") if l.startswith("flags")).split()
        fma = " fma" if "fma" in flags else " (no fma)"
    except (OSError, StopIteration):
        fma = " (fma unknown)"
    # glibc's ifuncs pick the FMA variants of exp, log, pow, sin and cos when the CPU has FMA: their bits differ.
    return "glibc %s %s%s" % (libc.gnu_get_libc_version().decode(), platform.machine(), fma)


def require_platform():
    """1.3.0's own bits are glibc 2.44's on x86_64 with FMA. Another machine, or a CPU without FMA, is refused: glibc
    computes other bits there. Another glibc version is allowed, and the digests decide (`--digests`): glibc's libm
    has given the same bits since its 2.28 rewrites, and scripts/golden/digests.txt holds 2.44's."""
    want = PROVENANCE.split("libm: ")[1]
    got = platform_provenance()
    if got == want:
        return
    if got.split(" ", 2)[2:] != want.split(" ", 2)[2:]:
        raise SystemExit("PROVENANCE: this corpus records %s, and this machine is %s" % (want, got))
    print("note: %s, not %s: `gen.py --digests` decides whether its bits are 2.44's" % (got, want))
REGEN = "# regenerate: python3 -I -B scripts/golden/gen.py ."
COLUMNS = "# columns: fn<TAB>class<TAB>inputs<TAB>outputs<TAB>note (tokens: scripts/golden/README.md)"
NOTE_CAP = 120


def bits(x):
    return struct.unpack("<Q", struct.pack("<d", x))[0]


def from_bits(b):
    return struct.unpack("<d", struct.pack("<Q", b & 0xFFFFFFFFFFFFFFFF))[0]


# Tokens are tuples: ("f", x), ("i", n), ("e", enum, variant), ("s", bytes), ("n",), ("E", variant), ("v", n).
def f(x):
    return ("f", float(x))


def i(n):
    n = int(n)
    if n >= 1 << 63:
        n -= 1 << 64
    return ("i", n)


def b(x):
    return ("i", 1 if x else 0)


def s(x):
    return ("s", x.encode("utf-8") if isinstance(x, str) else bytes(x))


def e(enum, variant):
    return ("e", enum, variant)


def none():
    return ("n",)


def err(variant):
    return ("E", variant)


def deser():
    return ("E", "Deserialize")


def v(n):
    return ("v", n)


def pct(data):
    out = []
    for byte in data:
        if 0x21 <= byte <= 0x7E and byte != 0x25:
            out.append(chr(byte))
        else:
            out.append("%%%02X" % byte)
    return "".join(out)


def wire(t):
    k = t[0]
    if k == "f":
        return "f:%016x" % bits(t[1])
    if k == "i":
        return "i:%d" % t[1]
    if k == "e":
        return "e:%s.%s" % (t[1], t[2])
    if k == "s":
        return "s:" + pct(t[1])
    if k == "n":
        return "n:"
    if k == "E":
        return "E:" + t[1]
    if k == "v":
        return "v:%d" % t[1]
    raise ValueError(t)


def human(t):
    k = t[0]
    if k == "f":
        return repr(t[1])
    if k == "i":
        return str(t[1])
    if k == "s":
        return repr(t[1])[1:]
    if k == "e":
        return "%s::%s" % (t[1], t[2])
    if k == "n":
        return "None"
    if k == "E":
        return "Err(%s)" % t[1]
    return "[%d]" % t[1]


def wire_list(toks):
    return " ".join(wire(t) for t in toks) if toks else "-"


class Module:
    def __init__(self, name):
        self.name = name
        self.rows = []

    def row(self, fn, cls, ins, outs):
        note = "%s(%s) -> %s" % (fn, ", ".join(human(t) for t in ins[:8]), ", ".join(human(t) for t in outs[:8]))
        if len(note) > NOTE_CAP:
            note = note[: NOTE_CAP - 1] + "…"
        self.rows.append("%s\t%s\t%s\t%s\t%s" % (fn, cls, wire_list(ins), wire_list(outs), note))

    def render(self):
        head = [
            "# pramana golden corpus, format 1: %s" % self.name,
            "# oracle: %s. Generated by scripts/golden; do not edit." % PROVENANCE,
            REGEN,
            COLUMNS,
            "# rows: %d" % len(self.rows),
        ]
        return "\n".join(head + self.rows) + "\n"


def parsed(toks):
    """Tokens as validate.py's parse_token reads them: f: a float, i: an int, the others their wire text."""
    out = []
    for t in toks:
        if t[0] == "f":
            out.append(t[1])
        elif t[0] == "i":
            out.append(t[1])
        else:
            out.append(wire(t))
    return out


def from_model(toks):
    """validate.py's parsed tokens back to tuples."""
    out = []
    for t in toks:
        if isinstance(t, float):
            out.append(f(t))
        elif isinstance(t, int):
            out.append(i(t))
        elif t.startswith("v:"):
            out.append(v(int(t[2:])))
        elif t.startswith("s:"):
            out.append(("s", urllib.parse.unquote_to_bytes(t[2:])))
        elif t.startswith("e:"):
            enum, var = t[2:].split(".", 1)
            out.append(e(enum, var))
        elif t.startswith("E:"):
            out.append(err(t[2:]))
        else:
            raise ValueError(t)
    return out



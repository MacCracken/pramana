"""`constants.tsv`: every constant src/constants.cyr defines, its Rust path and value (port plan §5 step 6), read from
rust-old/src's text by validate.py's own extractor; and the two Cyrius files generated from them, src/constants.cyr
and tests/constants_rows.cyr (write_sources)."""
import re
from decimal import Decimal
from pathlib import Path

from .models import V
from .tsv import Module, f, i, s, bits

ROOT = Path(__file__).resolve().parents[3]


def constants():
    return list(V.python_constants(ROOT).items())


def emit():
    m = Module("constants")
    for path, val in constants():
        m.row("const", "A", [s(path)], [f(val) if isinstance(val, float) else i(val)])
    return m


def public_paths():
    """`pub const` items at a module's top level: the only public constants (ai's two bounds)."""
    out = set()
    for p in sorted((ROOT / "rust-old" / "src").glob("*.rs")):
        for line in V.library_part(p.read_text(encoding="utf-8")).split("\n"):
            mm = re.match(r"pub const (\w+):", line)
            if mm:
                out.add(f"{p.stem}::{mm.group(1)}")
    return out


def cyr_name(path, public):
    body = path.replace("::consts::", "::").replace("::", "_").replace("[", "_").replace("]", "").upper()
    return ("PMN_" if public else "_PMN_") + body


def rust_display(x):
    """Rust's `{}` for a finite f64: the shortest round-trip digits, positional, never an exponent."""
    d = Decimal(repr(x))
    t = format(d, "f")
    if "." not in t:
        t += ".0"
    if t.startswith("-0") and x == 0.0 and str(x).startswith("-"):
        t = "-0.0"
    return t


def f64_literal(x):
    if x != x or x in (float("inf"), float("-inf")):
        return None
    lit = rust_display(x)
    if len(lit) > 64 or bits(float(lit)) != bits(x):
        return None
    return lit


def group(path):
    base = path.split("[")[0]
    return base.rsplit("::", 1)[0] if "::" in base else base


HEAD = """# pramana — the constants the port reads
#
# GENERATED by scripts/golden/gen.py from rust-old/src (pramana 1.3.0). Do not edit.
# Regenerate: python3 -I -B scripts/golden/gen.py . --only constants
#
# Every const item in rust-old/src's library code, and every Rust std float constant it names.
# Values come from the source text through Python's correctly rounded decimal parse, which rounds a literal as rustc
# does, or from the IEEE values for the std constants. tests/golden/constants.tsv pins each value, and
# probe_tables.py checks that the compiler reads each one back exactly.
#
# A float is a `const` with a positional decimal (an f64). A value with no short literal is a
# typed global holding its bit pattern: a hex `const` would be an integer.
"""

ROWS_HEAD = """# pramana — the constants rows' lookup, for tests/parity.tcyr
#
# GENERATED by scripts/golden/gen.py from rust-old/src (pramana 1.3.0). Do not edit.
# Regenerate: python3 -I -B scripts/golden/gen.py . --only constants
#
# For each tests/golden/constants.tsv path, the src/constants.cyr value it pins. Test code only:
# it needs tests/parity_core.cyr's `_par_eq`, `_par_got_f` and `_par_got_i` in scope.

# Appends the generated value of the golden path [np, np + nl) to the got list: 1 if the path is
# known, -1 (a defect) if not.
fn _par_constant_row(np, nl): i64 {
"""


def sources():
    pub = public_paths()
    cs = constants()
    out = [HEAD]
    last = ""
    for path, val in cs:
        g = group(path)
        if g != last:
            if g == "f64":
                out.append("\n# Rust std float constants (port-parity §1: the stdlib's F64_* names are untyped).\n")
                out.append("# UPSTREAM(L2): cyrius:docs/development/issues/2026-11-11-f64-min-max-drop-nan-only-as-first-operand.md\n")
                out.append("#   replace with the stdlib's typed F64_* constants once it has them; parity: the constants rows\n")
                out.append("#   (class A)\n")
            out.append(f"\n# Rust: {g}\n")
            last = g
        name = cyr_name(path, path in pub)
        if isinstance(val, int):
            out.append(f"const {name} = {val};\n")
        else:
            lit = f64_literal(val)
            out.append(f"const {name} = {lit};\n" if lit else f"var {name}: f64 = 0x{bits(val):016X};\n")
    rows = [ROWS_HEAD]
    for path, val in cs:
        name = cyr_name(path, path in pub)
        got = f"_par_got_f({name});" if isinstance(val, float) else f"_par_got_i({name});"
        rows.append(f"    if (_par_eq(np, nl, \"{path}\") == 1) {{\n        {got}\n        return 1;\n    }}\n")
    rows.append("    return 0 - 1;\n}\n")
    return "".join(out), "".join(rows)

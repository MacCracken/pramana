//! `src/constants.cyr` — every constant pramana's port reads, generated, never typed (port plan §5 step 6).
//!
//! Rules the output keeps (probed on 6.7.18 by the siblings and by pramana's step 4, port-parity §1):
//! - **Hex is never used in a `const`**, where it is an integer. A float constant is a `const` with a decimal literal,
//!   which is an f64.
//! - **There is no exponent notation**, so a decimal is written out positionally: Rust's `Display` for f64, the
//!   shortest round-trip digits, never an exponent. The lexer rounds it correctly, so the bits come back.
//! - **A value with no short literal** (±∞, NaN, or a positional form over 64 characters, like 1e-300 or `f64::MAX`)
//!   is a typed `f64` global holding its bit pattern. A hex word ≥ 2^52 in an `f64` slot is the warning-free
//!   boxed-float idiom, and no line goes past `cyrius lint`'s 120 characters.
//! - **Names** carry `PMN_` (public API) or `_PMN_` (private), then the Rust path (`consts::cyr_name`).
//!
//! Adapted from pravash's `t_constants.rs` / `cyr.rs`.

use crate::consts::{Const, Val, cyr_name};

/// A finite f64 as a Cyrius decimal literal, or None when it needs a bit-pattern global.
fn f64_literal(x: f64) -> Option<String> {
    if !x.is_finite() {
        return None;
    }
    let mut s = format!("{x}");
    if !s.contains('.') {
        s.push_str(".0");
    }
    if s.len() > 64 {
        return None;
    }
    // The lexer must give back exactly x: check the round trip here, as the Cyrius side will.
    match s.parse::<f64>() {
        Ok(y) if y.to_bits() == x.to_bits() => Some(s),
        _ => None,
    }
}

/// The definition line of one constant.
fn definition(c: &Const) -> String {
    let name = cyr_name(c);
    match c.val {
        Val::I(n) => format!("const {name} = {n};"),
        Val::F(x) => match f64_literal(x) {
            Some(lit) => format!("const {name} = {lit};"),
            None => format!("var {name}: f64 = 0x{:016X};", x.to_bits()),
        },
    }
}

/// The module part of a path, for grouping: `math::fdlibm::PP0` → `math::fdlibm`; `f64::NAN` → `f64`.
fn group(path: &str) -> &str {
    let base = path.split('[').next().unwrap_or(path);
    base.rsplit_once("::").map_or(base, |(g, _)| g)
}

pub fn emit(consts: &[Const], provenance: &str) -> String {
    let mut out = String::new();
    out.push_str("# pramana — the constants the port reads\n#\n");
    out.push_str(&format!("# GENERATED by scripts/golden from {provenance}. Do not edit.\n"));
    out.push_str("# Regenerate: (cd scripts/golden && cargo run --release --locked)\n#\n");
    out.push_str("# Every const item in rust-old/src's library code, and every Rust std float constant it names.\n");
    out.push_str("# Values come from the source through Rust's own literal parser, or from Rust itself for the std\n");
    out.push_str("# constants. scripts/golden/src/p_constants.rs proves the tables by recomputing the oracle's\n");
    out.push_str("# functions with them, tests/golden/constants.tsv pins each value, and probe_tables.py checks that\n");
    out.push_str("# the compiler reads each one back exactly.\n#\n");
    out.push_str("# A float is a `const` with a positional decimal (an f64). A value with no short literal is a\n");
    out.push_str("# typed global holding its bit pattern: a hex `const` would be an integer.\n");
    let mut last = "";
    for c in consts {
        let g = group(&c.path);
        if g != last {
            if g == "f64" {
                // The typed std float constants stand in for the stdlib's untyped F64_* (ledger L2).
                out.push_str("\n# Rust std float constants (port-parity §1: the stdlib's F64_* names are untyped).\n");
                out.push_str(
                    "# UPSTREAM(L2): cyrius:docs/development/issues/2026-11-11-f64-min-max-drop-nan-only-as-first-operand.md\n",
                );
                out.push_str("#   replace with the stdlib's typed F64_* constants once it has them; parity: the constants rows\n");
                out.push_str("#   (class A)\n");
            }
            out.push_str(&format!("\n# Rust: {g}\n"));
            last = g;
        }
        out.push_str(&definition(c));
        out.push('\n');
    }
    out
}

/// `tests/constants_rows.cyr`: for each `constants.tsv` path, the `src/constants.cyr` value it pins. Test code only:
/// it needs `tests/parity_core.cyr`'s `_par_eq`, `_par_got_f` and `_par_got_i` in scope.
pub fn emit_rows(consts: &[Const], provenance: &str) -> String {
    let mut out = String::new();
    out.push_str("# pramana — the constants rows' lookup, for tests/parity.tcyr\n#\n");
    out.push_str(&format!("# GENERATED by scripts/golden from {provenance}. Do not edit.\n"));
    out.push_str("# Regenerate: (cd scripts/golden && cargo run --release --locked)\n#\n");
    out.push_str("# For each tests/golden/constants.tsv path, the src/constants.cyr value it pins. Test code only:\n");
    out.push_str("# it needs tests/parity_core.cyr's `_par_eq`, `_par_got_f` and `_par_got_i` in scope.\n\n");
    out.push_str("# Appends the generated value of the golden path [np, np + nl) to the got list: 1 if the path is\n");
    out.push_str("# known, -1 (a defect) if not.\n");
    out.push_str("fn _par_constant_row(np, nl): i64 {\n");
    for c in consts {
        let name = cyr_name(c);
        let got = match c.val {
            Val::F(_) => format!("_par_got_f({name});"),
            Val::I(_) => format!("_par_got_i({name});"),
        };
        out.push_str(&format!(
            "    if (_par_eq(np, nl, \"{}\") == 1) {{\n        {got}\n        return 1;\n    }}\n",
            c.path
        ));
    }
    out.push_str("    return 0 - 1;\n}\n");
    out
}


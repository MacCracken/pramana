//! `golden` — writes everything the Cyrius port derives from the frozen Rust pramana 1.3.0 in `rust-old/` (with
//! its hidden `oracle` hooks):
//! - the golden corpus, `tests/golden/<module>.tsv` (port plan §5 step 5);
//! - the generated Cyrius sources, `src/constants.cyr` and later data modules (step 6).
//!
//! ```sh
//! cd scripts/golden
//! cargo run --release --locked              # write
//! cargo run --release --locked -- --check   # verify; exit 1 on any difference
//! ```
//!
//! Run it from this directory, so rustup applies `rust-toolchain.toml` (the recording toolchain, 1.100.0).
//!
//! `--check` regenerates every output in memory and compares it byte for byte with the committed file. It exits 1
//! if any output differs or is missing, if a `.tsv` has no emitter, or if a file was recorded under another
//! provenance (pramana, hisab, rustc, or the glibc platform: `glibc.rs`). The transcendental rows are glibc's bits,
//! and the inline code is rustc's, so a corpus can only be checked where it was made.
//!
//! The correctly rounded rows (`*.cr.tsv`) and the reference rows (`*.ref.tsv`) are `validate.py`'s outputs, from
//! MPFR; this program leaves them alone.
//!
//! Adapted from pravash's `scripts/oracle/` (same format, same rules), which took it from impetus, kimiya and
//! tanmatra. Modules are added at the start of their milestone: `constants` and `math` (M0); …
//!
//! Before writing anything it extracts every constant from `rust-old/src` (`consts.rs`) and proves the tables by
//! recomputing the oracle's functions with them (`p_constants.rs`); a failed proof writes nothing. The mutation
//! hook `GOLDEN_NUDGE=<path>` moves one extracted f64 by an ulp, reports which proof catches it, and never writes.

mod consts;
mod glibc;
mod grids;
mod m_constants;
mod m_fmt;
mod m_math;
mod p_constants;
mod t_constants;
mod tsv;

use std::collections::BTreeSet;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::ExitCode;

/// Every golden emitter, in file-name order.
fn golden_modules(constants: &[consts::Const]) -> Vec<tsv::Module> {
    vec![m_constants::emit(constants), m_fmt::emit(), m_math::emit()]
}

/// One generated file: its path from the repo root, its contents, and a summary.
struct Output {
    rel: String,
    text: String,
    summary: String,
}

fn read(path: &Path) -> Result<String, String> {
    fs::read_to_string(path).map_err(|e| format!("{}: {e}", path.display()))
}

/// `version = "x"` from the first line that starts with it (the `[package]` one).
fn toml_version(text: &str) -> Option<&str> {
    let line = text.lines().find(|l| l.starts_with("version = \""))?;
    line.strip_prefix("version = \"")?.strip_suffix('"')
}

/// The locked version of `crate_name` in a Cargo.lock (its first entry).
fn lock_version<'a>(lock: &'a str, crate_name: &str) -> Option<&'a str> {
    let needle = format!("name = \"{crate_name}\"\n");
    let at = lock.find(&needle)? + needle.len();
    let line = lock[at..].lines().next()?;
    line.strip_prefix("version = \"")?.strip_suffix('"')
}

/// `pramana 1.3.0 (rust-old/), hisab 1.4.0, rustc 1.100.0`: the oracle, its math, and its compiler.
fn oracle_provenance(root: &Path) -> Result<String, String> {
    let cargo = read(&root.join("rust-old/Cargo.toml"))?;
    let lock = read(&root.join("scripts/golden/Cargo.lock"))?;
    let pm = toml_version(&cargo).ok_or("rust-old/Cargo.toml: no version")?;
    let hs = lock_version(&lock, "hisab").ok_or("scripts/golden/Cargo.lock: no hisab")?;
    let rustc = env!("GOLDEN_RUSTC_VERSION");
    Ok(format!("pramana {pm} (rust-old/), hisab {hs}, rustc {rustc}"))
}

/// Write `out` to `root/rel`, or in check mode compare it. Returns false on a mismatch.
fn emit(root: &Path, check: bool, out: &Output) -> Result<bool, String> {
    let path: PathBuf = root.join(&out.rel);
    if !check {
        fs::write(&path, &out.text).map_err(|e| format!("{}: {e}", path.display()))?;
        println!("wrote    {} ({})", out.rel, out.summary);
        return Ok(true);
    }
    match fs::read_to_string(&path) {
        Ok(old) if old == out.text => {
            println!("ok       {} ({})", out.rel, out.summary);
            Ok(true)
        }
        Ok(_) => {
            println!("DIFFERS  {}", out.rel);
            Ok(false)
        }
        Err(_) => {
            println!("MISSING  {}", out.rel);
            Ok(false)
        }
    }
}

/// The provenance in a TSV's `# oracle:` header line: the text up to `. Generated by`.
fn recorded_provenance(text: &str) -> Option<String> {
    let line = text
        .lines()
        .take(5)
        .find_map(|l| l.strip_prefix("# oracle: "))?;
    Some(
        line.split_once(". Generated by")
            .map_or(line, |(p, _)| p)
            .to_string(),
    )
}

/// The generator's own `.tsv` names in `dir`, sorted. The `*.cr.tsv` and `*.ref.tsv` files are validate.py's.
fn tsv_names(dir: &Path) -> Vec<String> {
    let Ok(entries) = fs::read_dir(dir) else {
        return Vec::new();
    };
    let mut names: Vec<String> = entries
        .flatten()
        .map(|e| e.file_name().to_string_lossy().into_owned())
        .filter(|n| n.ends_with(".tsv") && !n.ends_with(".cr.tsv") && !n.ends_with(".ref.tsv"))
        .collect();
    names.sort();
    names
}

/// In check mode: every `.tsv` must have been recorded under the running provenance (oracle, compiler and glibc
/// platform), so a corpus made elsewhere is refused with a reason rather than as an anonymous DIFFERS.
fn check_provenance(dir: &Path, provenance: &str) -> bool {
    let mut ok = true;
    for name in tsv_names(dir) {
        let Ok(text) = fs::read_to_string(dir.join(&name)) else {
            continue;
        };
        match recorded_provenance(&text) {
            Some(p) if p == provenance => {}
            Some(p) => {
                println!(
                    "PROVENANCE tests/golden/{name}: recorded under `{p}`, running `{provenance}`. Its rows are \
                     that oracle's, compiler's and glibc's bits: check it where it was recorded, or regenerate \
                     deliberately"
                );
                ok = false;
            }
            None => {
                println!("PROVENANCE tests/golden/{name}: no recorded provenance in its header");
                ok = false;
            }
        }
    }
    ok
}

fn run() -> Result<bool, String> {
    let check = std::env::args().skip(1).any(|a| a == "--check");
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
    let root = root
        .canonicalize()
        .map_err(|e| format!("{}: {e}", root.display()))?;
    let oracle = oracle_provenance(&root)?;
    let provenance = format!("{oracle}; libm: {}", glibc::platform());

    // The constants, then the proofs; a failed proof writes nothing.
    let nudge = std::env::var("GOLDEN_NUDGE").ok();
    let constants = consts::extract(&root, nudge.as_deref())?;
    let mut proven = true;
    for v in p_constants::prove(&constants) {
        match &v.failure {
            None => println!("proved   {} ({} cases)", v.name, v.checked),
            Some(why) => {
                println!("REFUSED  {}: {why}", v.name);
                proven = false;
            }
        }
    }
    if let Some(n) = &nudge {
        println!(
            "GOLDEN_NUDGE {n}: {} (the mutation hook never writes)",
            if proven { "NOT caught by any proof" } else { "caught" }
        );
        return Ok(false);
    }
    if !proven {
        return Err("a constant proof failed: nothing written".to_string());
    }
    let dir = root.join("tests/golden");
    if !check {
        fs::create_dir_all(&dir).map_err(|e| format!("{}: {e}", dir.display()))?;
    }

    let mut ok = true;
    if check {
        ok &= check_provenance(&dir, &provenance);
    }

    let mut outputs = Vec::new();
    let mut emitted = BTreeSet::new();
    for module in golden_modules(&constants) {
        let name = format!("{}.tsv", module.name);
        emitted.insert(name.clone());
        outputs.push(Output {
            rel: format!("tests/golden/{name}"),
            text: module.render(&provenance),
            summary: format!("{} rows", module.len()),
        });
    }
    // The harness reads this list, so a module added here can't go untested: without a dispatcher it is
    // reported as pending, row by row.
    let mut index =
        String::from("# pramana golden corpus: one module per line; tests/parity.tcyr replays each\n");
    for name in &emitted {
        index.push_str(name.trim_end_matches(".tsv"));
        index.push('\n');
    }
    outputs.push(Output {
        rel: "src/constants.cyr".to_string(),
        text: t_constants::emit(&constants, &oracle),
        summary: format!("{} constants", constants.len()),
    });
    outputs.push(Output {
        rel: "tests/constants_rows.cyr".to_string(),
        text: t_constants::emit_rows(&constants, &oracle),
        summary: format!("{} lookups", constants.len()),
    });
    outputs.push(Output {
        rel: "tests/golden/modules.txt".to_string(),
        summary: format!("{} modules", emitted.len()),
        text: index,
    });

    for out in &outputs {
        ok &= emit(&root, check, out)?;
    }

    // A .tsv with no emitter is stale: the harness would test rows nobody regenerates.
    for name in tsv_names(&dir) {
        if !emitted.contains(&name) {
            println!("STALE    tests/golden/{name} (no emitter)");
            ok = false;
        }
    }
    Ok(ok)
}

fn main() -> ExitCode {
    match run() {
        Ok(true) => ExitCode::SUCCESS,
        Ok(false) => ExitCode::from(1),
        Err(e) => {
            eprintln!("golden: {e}");
            ExitCode::from(2)
        }
    }
}

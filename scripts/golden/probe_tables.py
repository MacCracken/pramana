"""probe_tables.py — compile every generated Cyrius value and compare its bits with the golden rows (M0 step 6).

    python3 -I -B scripts/golden/probe_tables.py .

The generator writes `src/constants.cyr` and pins every value in `tests/golden/constants.tsv`. This checks the step in
between: that the Cyrius compiler reads each generated literal or bit pattern back as exactly the oracle's value.
- For every constants row, it derives the Cyrius name by the generator's rule (`consts::cyr_name`).
- It writes a probe program that includes `src/constants.cyr` and prints each value's word.
- It builds the probe with `cyrius build` from the repo root, warning-free, and runs it.
- It compares each word with the row.

Exit status 1 on any mismatch, any build warning, a row with no generated name, or a generated name with no row.
Adapted from pravash's `probe_tables.py`.
"""

import re
import subprocess
import sys
from pathlib import Path


def cyr_name(path, public):
    body = path.replace("::consts::", "::").replace("::", "_").replace("[", "_").replace("]", "").upper()
    return ("PMN_" if public else "_PMN_") + body


def unpct(s):
    return re.sub(r"%([0-9A-F]{2})", lambda m: chr(int(m.group(1), 16)), s)


def main():
    root = Path(sys.argv[1] if len(sys.argv) > 1 else ".").resolve()
    generated = (root / "src/constants.cyr").read_text(encoding="utf-8")
    defined = {m.group(2) for m in re.finditer(r"^(const|var) (_?PMN_\w+)", generated, re.M)}

    rows = {}
    for line in (root / "tests/golden/constants.tsv").read_text(encoding="utf-8").splitlines()[5:]:
        _fn, _cls, ins, outs, _note = line.split("\t")
        path = unpct(ins[2:])
        public_name = cyr_name(path, True)
        name = public_name if public_name in defined else cyr_name(path, False)
        kind, val = outs.split(":", 1)
        rows[name] = int(val, 16) if kind == "f" else int(val) & ((1 << 64) - 1)

    fails = [f"{n}: a golden row with no generated value" for n in sorted(set(rows) - defined)]
    fails += [f"{n}: generated with no golden row" for n in sorted(defined - set(rows))]

    names = sorted(set(rows) & defined)
    body = [f'    put("{n}\\t"); fmt_hex0x({n}); println("");' for n in names]
    probe = "\n".join([
        "# Generated by scripts/golden/probe_tables.py; not part of the library.",
        'include "src/constants.cyr"',
        "",
        "# Write a C string to stdout.",
        "fn put(s: cstring): i64 {",
        "    print(s, strlen(s));",
        "    return 0;",
        "}",
        "",
        "# Print every constant's word.",
        "fn main(): i64 {",
        "    alloc_init();",
        *body,
        "    return 0;",
        "}",
        "",
        "var rc = main();",
        "sys_exit_group(rc);",
        "",
    ])
    build = root / "build"
    build.mkdir(exist_ok=True)
    src = build / "probe_tables.cyr"
    src.write_text(probe, encoding="utf-8")
    exe = build / "probe_tables"
    b = subprocess.run(["cyrius", "build", str(src), str(exe)], cwd=root, capture_output=True, text=True)
    out = b.stdout + b.stderr
    if b.returncode != 0:
        print(out)
        print("probe_tables: the probe did not build")
        return 1
    warnings = [l for l in out.splitlines() if "warning" in l.lower()]
    fails += [f"build warning: {w}" for w in warnings]
    r = subprocess.run([str(exe)], capture_output=True, text=True)
    seen = 0
    for line in r.stdout.splitlines():
        name, word = line.split("\t")
        got = int(word, 16) & ((1 << 64) - 1)
        seen += 1
        if got != rows[name]:
            fails.append(f"{name}: compiled to {got:#018x}, the row says {rows[name]:#018x}")
    if seen != len(names):
        fails.append(f"the probe printed {seen} values, expected {len(names)}")
    for f in fails:
        print("FAILED:", f)
    print(f"probe_tables: {len(names)} constants compiled, " + ("all exact" if not fails else f"{len(fails)} failures"))
    return 1 if fails else 0


if __name__ == "__main__":
    sys.exit(main())

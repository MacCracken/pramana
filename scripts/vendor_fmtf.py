"""Vendors impetus's serde_json f64 printer into src/fmtf.cyr (ledger L10; port plan D5, ADR 007 row 7).

pramana writes serde_json's text byte for byte (D5 as amended after probe P7, which checked impetus's printer on
280,562 doubles: 0 differ). impetus 2.0.0's src/fmtf.cyr computes the shortest round-trip digits with Burger &
Dybvig's free-format algorithm on a small bignum (its ADR 0010), and `im_fmt_f64_json` writes them in serde_json's
form. This copies the dependency closure of that function (functions and globals with their doc comments, in
impetus's source order) from impetus's git tag VERSION, renaming `_im_` → `_pmn_im_`, `_IM_` → `_PMN_IM_` and
`im_fmt_f64_json` → `_pmn_fmt_f64_json`. impetus takes an f64's bits from its own mathx.cyr (`_im_bits`), so the
header defines `_pmn_im_bits`. Rust's Display form isn't vendored: no output the port keeps uses it. Usage, from the
repo root:

    python3 -I -B scripts/vendor_fmtf.py .            # write src/fmtf.cyr from ../impetus
    python3 -I -B scripts/vendor_fmtf.py . --check    # exit 1 when src/fmtf.cyr differs from what ../impetus gives

Without ../impetus (CI checks out pramana alone), `--check` reports "unverified" and exits 0. Stdlib only.
"""

import os
import re
import subprocess
import sys

ROOT = os.path.abspath(sys.argv[1] if len(sys.argv) > 1 and not sys.argv[1].startswith("-") else ".")
CHECK = "--check" in sys.argv
IMPETUS = os.path.join(os.path.dirname(ROOT), "impetus")
VERSION = "2.0.0"
ROOTS = ["im_fmt_f64_json"]
OUT = os.path.join(ROOT, "src", "fmtf.cyr")


def items(text):
    """{name: (start, end)} of the top-level `fn` and `var` items of text, each starting at its doc comment."""
    out = {}
    lines = text.split("\n")
    offs = [0]
    for ln in lines:
        offs.append(offs[-1] + len(ln) + 1)
    pat = re.compile(r"^(?:fn (\w+)\(|var (\w+))")
    for i, ln in enumerate(lines):
        m = pat.match(ln)
        if not m:
            continue
        j = i
        while j > 0 and lines[j - 1].startswith("#"):
            j -= 1
        k = i
        if m.group(1):
            while lines[k] != "}":
                k += 1
        elif "{" in ln and "}" not in ln:
            while not lines[k].startswith("}"):
                k += 1
        out[m.group(1) or m.group(2)] = (offs[j], offs[k + 1])
    return out


def rename(text):
    text = re.sub(r"\bim_fmt_f64_json\b", "_pmn_fmt_f64_json", text)
    text = re.sub(r"\b_im_", "_pmn_im_", text)
    return re.sub(r"\b_IM_", "_PMN_IM_", text)


def main():
    if not os.path.isdir(os.path.join(IMPETUS, ".git")):
        if CHECK:
            print("vendor_fmtf: unverified (../impetus is not checked out)")
            return 0
        print("vendor_fmtf: ../impetus not found", file=sys.stderr)
        return 1
    try:
        src = subprocess.run(["git", "-C", IMPETUS, "show", f"{VERSION}:src/fmtf.cyr"], capture_output=True,
                             text=True, check=True).stdout
        commit = subprocess.run(["git", "-C", IMPETUS, "rev-parse", "--short", VERSION], capture_output=True,
                                text=True, check=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError) as e:
        print(f"vendor_fmtf: can't read impetus's tag {VERSION}: {e}", file=sys.stderr)
        return 1
    defs = items(src)
    seen, stack = set(), list(ROOTS)
    while stack:
        name = stack.pop()
        if name in seen:
            continue
        seen.add(name)
        a, b = defs[name]
        for ref in re.findall(r"\b(_?[iI][mM]_\w+)\b", src[a:b]):
            if ref in defs and ref not in seen:
                stack.append(ref)
    order = sorted(seen, key=lambda n: defs[n][0])
    origin = f"impetus {VERSION} (tag {VERSION}, {commit})"
    head = [
        f"# fmtf.cyr — an f64 as serde_json 1.0.154 writes it, vendored from {origin} src/fmtf.cyr.",
        "# GENERATED by scripts/vendor_fmtf.py: do not edit. Regenerate: python3 -I -B scripts/vendor_fmtf.py .",
        "# (--check verifies it against ../impetus)",
        "#",
        "# Port plan D5 as amended (ADR 007 row 7): pramana's JSON writes serde_json's text byte for byte, and bayan's",
        "# Grisu2 printer differs on 9,714 of 280,562 doubles (probe P7). `_pmn_fmt_f64_json(sb, x)` is impetus's",
        "# `im_fmt_f64_json`: the shortest round-trip digits by Burger & Dybvig on a small bignum (impetus ADR 0010),",
        "# ties to the even digit as serde_json's zmij, positional for decimal exponents −5 … 15 with \".0\" on an",
        "# integer, otherwise d.ddde±x, and `null` for NaN and ±∞. tests/golden/fmt.tsv pins it against serde_json on",
        f"# 25,200 doubles. {len(order)} items, in impetus's source order, renamed `_im_` → `_pmn_im_`, `_IM_` →",
        "# `_PMN_IM_`; the comments below are impetus's. impetus is GPL-3.0-only, as pramana is.",
        "# UPSTREAM(L10): bayan:docs/development/issues/2026-11-11-no-serde-compatible-shortest-f64-printer.md",
        "#   replace with bayan_f64_to_json_serde once it ships; parity: tests/golden/fmt.tsv and every JSON text row",
        "",
        "# An f64's bits as a word (impetus takes `_im_bits` from its mathx.cyr): an untyped parameter, an i64 return.",
        "#must_use",
        "fn _pmn_im_bits(x): i64 {",
        "    return x;",
        "}",
        "",
        "",
    ]
    text = "\n".join(head) + rename("".join(src[defs[n][0]:defs[n][1]] + "\n" for n in order))
    text = text.rstrip("\n") + "\n"
    if CHECK:
        try:
            with open(OUT, encoding="utf-8") as f:
                old = f.read()
        except FileNotFoundError:
            old = None
        if old != text:
            print("vendor_fmtf: src/fmtf.cyr is stale (regenerate: python3 -I -B scripts/vendor_fmtf.py .)")
            return 1
        print(f"vendor_fmtf: ok ({origin}: {len(order)} items)")
        return 0
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)
    print(f"wrote src/fmtf.cyr: {len(order)} items, {text.count(chr(10))} lines, from {origin}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
